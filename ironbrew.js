/**
 * KAIRO ENGINE // IronBrew Obfuscator Detector & Deobfuscator
 * Target: Luau scripts obfuscated by IronBrew / IronBrew 2 (IB2)
 * Signature: lIllIl variable naming, custom VM, XOR string encryption, CFF
 */

// ============================================================
// SECTION 1: DETECTION ENGINE
// ============================================================

export class IronBrewDetector {
    constructor() {
        this.layers = [
            { name: 'SignatureScan', weight: 0.25, run: this.signatureScan.bind(this) },
            { name: 'VariableNamingPattern', weight: 0.25, run: this.variableNamingPattern.bind(this) },
            { name: 'VMStructureDetection', weight: 0.20, run: this.vmStructureDetection.bind(this) },
            { name: 'StringEncryptionPattern', weight: 0.15, run: this.stringEncryptionPattern.bind(this) },
            { name: 'ControlFlowPattern', weight: 0.10, run: this.controlFlowPattern.bind(this) },
            { name: 'HeuristicAnalysis', weight: 0.05, run: this.heuristicAnalysis.bind(this) },
        ];
    }

    detect(code) {
        if (!code || typeof code !== 'string') {
            return { isIronBrew: false, confidence: 0, version: 'unknown', layers: [], error: 'Empty input' };
        }

        const results = [];
        let totalConfidence = 0;

        for (const layer of this.layers) {
            try {
                const layerResult = layer.run(code);
                results.push({
                    layer: layer.name,
                    confidence: layerResult.confidence,
                    evidence: layerResult.evidence || [],
                    versionHint: layerResult.versionHint || null,
                });
                totalConfidence += layerResult.confidence * layer.weight;
            } catch (err) {
                results.push({ layer: layer.name, confidence: 0, error: err.message });
            }
        }

        const isIronBrew = totalConfidence >= 0.50;
        const version = this.inferVersion(results, code);

        return {
            isIronBrew,
            confidence: Math.min(totalConfidence, 1.0),
            version,
            layers: results,
        };
    }

    // --- Layer 1: Signature / Watermark ---
    signatureScan(code) {
        const evidence = [];
        let confidence = 0;

        const signatures = [
            { pattern: /ironbrew/i, label: 'IronBrew keyword' },
            { pattern: /iron[_-]?brew/i, label: 'Iron-Brew variant' },
            { pattern: /--\s*\[\[\s*IronBrew/i, label: 'IronBrew header comment' },
            { pattern: /IRONBREW_V[0-9]/i, label: 'Version tag' },
            { pattern: /Generated by IronBrew/i, label: 'Generator signature' },
            { pattern: /IronBrew\s+2/i, label: 'IronBrew 2 tag' },
            { pattern: /IB2/i, label: 'IB2 abbreviation' },
        ];

        for (const sig of signatures) {
            if (sig.pattern.test(code)) {
                evidence.push(sig.label);
                confidence += 0.20;
            }
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 2: Variable Naming Pattern (KHAS IRONBREW) ---
    variableNamingPattern(code) {
        const evidence = [];
        let confidence = 0;

        // IronBrew signature: variable dengan mix lowercase L dan uppercase I
        // Contoh: lIllIl, IlIlII, lIIllI, IllIll
        // Pattern: kombinasi 'l' (lowercase L) dan 'I' (uppercase i) saja
        const ironBrewPattern = /\b([lI]{4,})\b/g;
        const ironMatches = [...code.matchAll(ironBrewPattern)];

        // Filter: harus ada mix lowercase L dan uppercase I
        const validIronVars = ironMatches.filter(m => {
            const v = m[1];
            return /[l]/.test(v) && /[I]/.test(v) && v.length >= 4;
        });

        if (validIronVars.length >= 10) {
            evidence.push(`IronBrew-style variables (lI mix): ${validIronVars.length}`);
            confidence += 0.45;
        } else if (validIronVars.length >= 5) {
            evidence.push(`IronBrew-style variables (lI mix): ${validIronVars.length}`);
            confidence += 0.25;
        } else if (validIronVars.length >= 2) {
            evidence.push(`IronBrew-style variables (lI mix): ${validIronVars.length}`);
            confidence += 0.10;
        }

        // Ratio: IronBrew vars / total vars
        const allVars = code.match(/local\s+([a-zA-Z_][a-zA-Z0-9_]*)/g) || [];
        const ironStyleVars = allVars.filter(v => {
            const name = v.replace('local ', '');
            return /^[lI]{4,}$/.test(name) && /[l]/.test(name) && /[I]/.test(name);
        });
        const ratio = allVars.length > 0 ? ironStyleVars.length / allVars.length : 0;

        if (ratio > 0.4) {
            evidence.push(`IronBrew variable ratio: ${(ratio * 100).toFixed(1)}%`);
            confidence += 0.30;
        } else if (ratio > 0.2) {
            evidence.push(`IronBrew variable ratio: ${(ratio * 100).toFixed(1)}%`);
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 3: VM Structure Detection ---
    vmStructureDetection(code) {
        const evidence = [];
        let confidence = 0;

        // VM dispatch table: local OPCODES = { [0] = function() ... end, ... }
        const dispatchPattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{[\s\S]*?\[\d+\]\s*=\s*function/g;
        const dispatchMatches = code.match(dispatchPattern);
        if (dispatchMatches && dispatchMatches.length >= 5) {
            evidence.push(`VM dispatch table: ${dispatchMatches.length} opcodes`);
            confidence += 0.35;
        }

        // Bytecode array panjang
        const bytecodePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{\s*[\d\s,]{80,}\s*\}/;
        if (bytecodePattern.test(code)) {
            evidence.push('Bytecode array detected');
            confidence += 0.20;
        }

        // VM loop: while true do ... if opcode == X then
        const vmLoopPattern = /while\s+true\s+do[\s\S]{300,}if\s+[a-zA-Z_][a-zA-Z0-9_]*\s*==\s*\d+/;
        if (vmLoopPattern.test(code)) {
            evidence.push('VM dispatch loop detected');
            confidence += 0.20;
        }

        // Stack operations
        const stackPattern = /table\.insert\([^,]+,\s*[^)]+\)|table\.remove\([^)]+\)/g;
        const stackMatches = code.match(stackPattern);
        if (stackMatches && stackMatches.length >= 8) {
            evidence.push(`Stack operations: ${stackMatches.length}`);
            confidence += 0.15;
        }

        // PC (program counter) variable
        const pcPattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*0[\s\S]*?while\s+true\s+do[\s\S]*?\1\s*=\s*\1\s*\+\s*1/;
        if (pcPattern.test(code)) {
            evidence.push('Program counter (PC) pattern detected');
            confidence += 0.20;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 4: String Encryption Pattern ---
    stringEncryptionPattern(code) {
        const evidence = [];
        let confidence = 0;

        // XOR pattern
        const xorPattern = /bit32\.bxor\s*\(\s*\d+\s*,\s*\d+\s*\)/g;
        const xorMatches = code.match(xorPattern);
        if (xorMatches && xorMatches.length >= 5) {
            evidence.push(`XOR operations: ${xorMatches.length}`);
            confidence += 0.25;
        }

        // string.char + bit32 kombinasi
        const charBxorPattern = /string\.char\s*\([^)]*bit32\.bxor[^)]*\)/g;
        const charBxorMatches = code.match(charBxorPattern);
        if (charBxorMatches && charBxorMatches.length >= 3) {
            evidence.push(`string.char + bit32.bxor: ${charBxorMatches.length}`);
            confidence += 0.20;
        }

        // Decrypt function dengan loop
        const decryptFuncPattern = /function\s+[a-zA-Z_][a-zA-Z0-9_]*\s*\([^)]*\)[\s\S]{80,}for\s+[a-zA-Z_][a-zA-Z0-9_]*\s*=\s*\d+\s*,\s*#[\s\S]*?return\s+string\.char/g;
        if (decryptFuncPattern.test(code)) {
            evidence.push('String decryption function with loop detected');
            confidence += 0.25;
        }

        // Encrypted string table
        const stringTablePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{\s*"[^"]{10,}"[\s\S]*?\}/;
        if (stringTablePattern.test(code)) {
            evidence.push('Encrypted string table');
            confidence += 0.15;
        }

        // Multi-layer: decrypt function yang dipanggil berkali-kali
        const multiDecryptPattern = /([a-zA-Z_][a-zA-Z0-9_]*)\s*\(\s*\1\s*\(/g;
        const multiMatches = code.match(multiDecryptPattern);
        if (multiMatches && multiMatches.length >= 2) {
            evidence.push(`Multi-layer decryption: ${multiMatches.length}`);
            confidence += 0.20;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 5: Control Flow Pattern ---
    controlFlowPattern(code) {
        const evidence = [];
        let confidence = 0;

        // CFF: state variable + while true + if/elseif chain
        const cffPattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*(0x[0-9a-fA-F]+|\d+)[\s\S]*?while\s+true\s+do[\s\S]*?(?:if|elseif)\s+\1\s*==/;
        if (cffPattern.test(code)) {
            evidence.push('Control flow flattening (state-based) detected');
            confidence += 0.35;
        }

        // Multiple state assignments dalam loop
        const stateAssignPattern = /while\s+true\s+do[\s\S]*?[a-zA-Z_][a-zA-Z0-9_]*\s*=\s*(0x[0-9a-fA-F]+|\d+)[\s\S]*?[a-zA-Z_][a-zA-Z0-9_]*\s*=\s*(0x[0-9a-fA-F]+|\d+)/g;
        const stateMatches = code.match(stateAssignPattern);
        if (stateMatches && stateMatches.length >= 3) {
            evidence.push(`State transitions: ${stateMatches.length}`);
            confidence += 0.20;
        }

        // Opaque predicates kompleks
        const opaquePattern = /if\s+\([^)]{20,}\)\s*then\s*(return|break|error)/g;
        const opaqueMatches = code.match(opaquePattern);
        if (opaqueMatches && opaqueMatches.length >= 2) {
            evidence.push(`Opaque predicates: ${opaqueMatches.length}`);
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 6: Heuristic Analysis ---
    heuristicAnalysis(code) {
        const evidence = [];
        let confidence = 0;

        // High entropy strings
        const stringLiterals = code.match(/"([^"\\]|\\.)*"/g) || [];
        let highEntropyStrings = 0;
        for (const s of stringLiterals) {
            if (this.calculateEntropy(s) > 4.5 && s.length > 20) {
                highEntropyStrings++;
            }
        }
        if (highEntropyStrings > 5) {
            evidence.push(`High-entropy strings: ${highEntropyStrings}`);
            confidence += 0.25;
        }

        // Minified structure (1-3 lines raksasa)
        const lines = code.split('\n').filter(l => l.trim().length > 0);
        const avgLineLength = code.length / Math.max(lines.length, 1);
        if (avgLineLength > 5000 && lines.length < 10) {
            evidence.push(`Minified: ${lines.length} lines, avg ${avgLineLength.toFixed(0)} chars/line`);
            confidence += 0.20;
        }

        // Function density
        const functionCount = (code.match(/\bfunction\b/g) || []).length;
        const localCount = (code.match(/\blocal\b/g) || []).length;
        if (localCount > 0 && functionCount / localCount > 0.3) {
            evidence.push(`High function/local ratio: ${(functionCount / localCount).toFixed(2)}`);
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    calculateEntropy(str) {
        if (!str || str.length === 0) return 0;
        const freq = {};
        for (const c of str) freq[c] = (freq[c] || 0) + 1;
        let entropy = 0;
        const len = str.length;
        for (const c in freq) {
            const p = freq[c] / len;
            if (p > 0) entropy -= p * Math.log2(p);
        }
        return entropy;
    }

    inferVersion(results, code) {
        const vm = results.find(r => r.layer === 'VMStructureDetection');
        const cff = results.find(r => r.layer === 'ControlFlowPattern');
        const sig = results.find(r => r.layer === 'SignatureScan');

        if (vm && vm.confidence > 0.5 && cff && cff.confidence > 0.3) {
            return 'v2-vm-cff';
        }
        if (vm && vm.confidence > 0.5) {
            return 'v2-vm';
        }
        if (sig && sig.confidence > 0.2) {
            return 'v1-legacy';
        }
        return 'unknown';
    }
}


// ============================================================
// SECTION 2: DEOBFUSCATION ENGINE
// ============================================================

export class IronBrewDeobfuscator {
    constructor() {
        this.levels = [
            { name: 'BasicCleanup', run: this.level1BasicCleanup.bind(this) },
            { name: 'StringDecryption', run: this.level2StringDecryption.bind(this) },
            { name: 'ConstantDecryption', run: this.level3ConstantDecryption.bind(this) },
            { name: 'VariableRenaming', run: this.level4VariableRenaming.bind(this) },
            { name: 'ControlFlowUnflattening', run: this.level5CFFUnflattening.bind(this) },
            { name: 'VMMetadataExtraction', run: this.level6VMMetadataExtraction.bind(this) },
            { name: 'AntiTamperBypass', run: this.level7AntiTamperBypass.bind(this) },
        ];
    }

    deobfuscate(code, detectionResult = null) {
        if (!code) return { success: false, deobfuscatedCode: '', appliedLevels: [], notes: 'Empty input' };

        let current = code;
        const appliedLevels = [];
        const notes = [];

        const orderedLevels = this.orderLevelsByHint(detectionResult);

        for (const level of orderedLevels) {
            try {
                const before = current;
                const result = level.run(current);

                if (result.changed && result.code !== before) {
                    current = result.code;
                    appliedLevels.push({
                        level: level.name,
                        changes: result.changes || 0,
                        notes: result.notes || null,
                    });

                    if (this.isClean(current)) {
                        notes.push(`Early exit after ${level.name}`);
                        break;
                    }
                }
            } catch (err) {
                notes.push(`${level.name} failed: ${err.message}`);
            }
        }

        return {
            success: appliedLevels.length > 0,
            deobfuscatedCode: current,
            appliedLevels,
            notes: notes.join(' | '),
            finalEntropy: this.calculateEntropy(current),
        };
    }

    orderLevelsByHint(detection) {
        if (!detection || !detection.version) return this.levels;

        const v = detection.version;
        if (v === 'v2-vm-cff') {
            return [
                this.levels[1], // String
                this.levels[2], // Constant
                this.levels[4], // CFF
                this.levels[5], // VM
                this.levels[0], // Cleanup
                this.levels[3], // Rename
                this.levels[6], // AntiTamper
            ];
        }
        if (v === 'v2-vm') {
            return [
                this.levels[1], // String
                this.levels[2], // Constant
                this.levels[5], // VM
                this.levels[0], // Cleanup
                this.levels[3], // Rename
                this.levels[4], // CFF
                this.levels[6], // AntiTamper
            ];
        }
        return this.levels;
    }

    // --- LEVEL 1: Basic Cleanup ---
    level1BasicCleanup(code) {
        let result = code;
        let changes = 0;

        // Hapus watermark IronBrew
        const before = result;
        result = result.replace(/--\s*\[\[\s*IronBrew[\s\S]*?\]\]/gi, '');
        result = result.replace(/--\s*Generated by IronBrew.*/gi, '');
        result = result.replace(/--\s*IronBrew\s+2.*/gi, '');
        if (result !== before) changes++;

        // Hapus komentar kosong beruntun
        result = result.replace(/(--[^\n]*\n){3,}/g, '--\n');

        // Opaque predicate sederhana: if (x == x) then ... end
        const opaquePattern = /if\s+\(([^)]{10,})\)\s*then\s*([\s\S]*?)\s*end/g;
        result = result.replace(opaquePattern, (match, cond, body) => {
            if (/^\s*\(?[a-zA-Z_0-9]+\s*==\s*\1\)?\s*$/.test(cond) || /^\s*\(?\s*0\s*==\s*0\s*\)?\s*$/.test(cond)) {
                changes++;
                return body.trim();
            }
            return match;
        });

        // Hapus dead code setelah return
        result = result.replace(/(return[^\n]*)\n[\s\S]*?(\n\s*end)/g, (match, ret, end) => {
            changes++;
            return ret + end;
        });

        return { code: result, changed: result !== code, changes };
    }

    // --- LEVEL 2: String Decryption ---
    level2StringDecryption(code) {
        let result = code;
        let changes = 0;

        // Pattern 1: string.char(a, b, c) langsung
        result = result.replace(/string\.char\(([\d\s,]+)\)/g, (match, args) => {
            try {
                const bytes = args.split(',').map(s => parseInt(s.trim(), 10));
                if (bytes.every(n => !isNaN(n) && n >= 0 && n <= 255)) {
                    changes++;
                    return JSON.stringify(String.fromCharCode(...bytes));
                }
            } catch (e) { /* ignore */ }
            return match;
        });

        // Pattern 2: XOR dengan key recovery
        // IronBrew sering: local KEY = N ... bit32.bxor(byte, KEY)
        const keyPatterns = [
            /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*(\d+)\s*(?:--\s*key)?/i,
            /local\s+([lI]{4,})\s*=\s*(\d+)/,
        ];

        let recoveredKey = null;
        let keyName = null;
        for (const kp of keyPatterns) {
            const km = code.match(kp);
            if (km) {
                const candidate = parseInt(km[2], 10);
                if (candidate >= 0 && candidate <= 255) {
                    recoveredKey = candidate;
                    keyName = km[1];
                    break;
                }
            }
        }

        if (recoveredKey !== null) {
            const xorCharPattern = /string\.char\(\s*((?:bit32\.bxor\(\s*\d+\s*,\s*[a-zA-Z_][a-zA-Z0-9_]*\s*\)\s*,?\s*)+)\)/g;
            result = result.replace(xorCharPattern, (match, inner) => {
                try {
                    const byteMatches = [...inner.matchAll(/bit32\.bxor\(\s*(\d+)\s*,\s*([a-zA-Z_][a-zA-Z0-9_]*)\s*\)/g)];
                    const bytes = byteMatches.map(m => {
                        const byte = parseInt(m[1], 10);
                        const varKey = m[2];
                        if (varKey === keyName) return byte ^ recoveredKey;
                        return byte;
                    });
                    if (bytes.length > 0 && bytes.every(n => n >= 0 && n <= 255)) {
                        changes++;
                        return JSON.stringify(String.fromCharCode(...bytes));
                    }
                } catch (e) { /* ignore */ }
                return match;
            });
        }

        // Pattern 3: String table lookup
        const tablePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{([^}]+)\}/;
        const tableMatch = result.match(tablePattern);
        if (tableMatch) {
            const tableName = tableMatch[1];
            const entries = tableMatch[2].split(',').map(s => {
                const trimmed = s.trim();
                if (/^["'].*["']$/.test(trimmed)) {
                    try { return JSON.parse(trimmed); } catch (e) { return null; }
                }
                const n = parseInt(trimmed, 10);
                return isNaN(n) ? null : n;
            });

            const lookupPattern = new RegExp(`${tableName}\\[(\\d+)\\]`, 'g');
            result = result.replace(lookupPattern, (match, idx) => {
                const i = parseInt(idx, 10);
                if (entries[i] !== null && entries[i] !== undefined) {
                    changes++;
                    return typeof entries[i] === 'string' ? JSON.stringify(entries[i]) : entries[i];
                }
                return match;
            });
        }

        // Pattern 4: Multi-layer decryption (decrypt(decrypt(x)))
        // Iterasi sampai stabil
        let prevResult = '';
        let iterations = 0;
        while (prevResult !== result && iterations < 3) {
            prevResult = result;
            result = result.replace(/([a-zA-Z_][a-zA-Z0-9_]*)\s*\(\s*([a-zA-Z_][a-zA-Z0-9_]*)\s*\(\s*("[^"]+")\s*\)\s*\)/g, (match, outer, inner, str) => {
                // Cek apakah inner dan outer adalah decrypt function
                const innerDef = new RegExp(`function\\s+${inner}\\s*\\([^)]*\\)[\\s\\S]*?return\\s+`);
                const outerDef = new RegExp(`function\\s+${outer}\\s*\\([^)]*\\)[\\s\\S]*?return\\s+`);
                if (innerDef.test(code) && outerDef.test(code)) {
                    changes++;
                    return `--[[ multi-layer decrypt: ${outer}(${inner}(${str})) ]]`;
                }
                return match;
            });
            iterations++;
        }

        return { code: result, changed: result !== code, changes, notes: changes > 0 ? `Decrypted ${changes} strings` : null };
    }

    // --- LEVEL 3: Constant Decryption ---
    level3ConstantDecryption(code) {
        let result = code;
        let changes = 0;

        // Fold arithmetic: (1 + 2) → 3
        result = result.replace(/\(\s*(\d+)\s*([+\-*/])\s*(\d+)\s*\)/g, (match, a, op, b) => {
            const na = parseInt(a, 10);
            const nb = parseInt(b, 10);
            let r;
            switch (op) {
                case '+': r = na + nb; break;
                case '-': r = na - nb; break;
                case '*': r = na * nb; break;
                case '/': r = nb !== 0 ? na / nb : null; break;
            }
            if (r !== null && r !== undefined && Number.isFinite(r)) {
                changes++;
                return String(r);
            }
            return match;
        });

        // Fold bit32 operations
        result = result.replace(/bit32\.bxor\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)/g, (match, a, b) => {
            changes++;
            return String(parseInt(a, 10) ^ parseInt(b, 10));
        });
        result = result.replace(/bit32\.band\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)/g, (match, a, b) => {
            changes++;
            return String(parseInt(a, 10) & parseInt(b, 10));
        });
        result = result.replace(/bit32\.bor\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)/g, (match, a, b) => {
            changes++;
            return String(parseInt(a, 10) | parseInt(b, 10));
        });
        result = result.replace(/bit32\.lshift\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)/g, (match, a, b) => {
            changes++;
            return String(parseInt(a, 10) << parseInt(b, 10));
        });
        result = result.replace(/bit32\.rshift\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)/g, (match, a, b) => {
            changes++;
            return String(parseInt(a, 10) >>> parseInt(b, 10));
        });

        // Fold nested: ((1 + 2) * 3) → 9
        let prevResult = '';
        let iterations = 0;
        while (prevResult !== result && iterations < 5) {
            prevResult = result;
            result = result.replace(/\(\s*(\d+)\s*([+\-*/])\s*(\d+)\s*\)/g, (match, a, op, b) => {
                const na = parseInt(a, 10);
                const nb = parseInt(b, 10);
                let r;
                switch (op) {
                    case '+': r = na + nb; break;
                    case '-': r = na - nb; break;
                    case '*': r = na * nb; break;
                    case '/': r = nb !== 0 ? na / nb : null; break;
                }
                if (r !== null && r !== undefined && Number.isFinite(r)) {
                    changes++;
                    return String(r);
                }
                return match;
            });
            iterations++;
        }

        return { code: result, changed: result !== code, changes, notes: changes > 0 ? `Folded ${changes} constant expressions` : null };
    }

    // --- LEVEL 4: Variable Renaming ---
    level4VariableRenaming(code) {
        let result = code;
        let changes = 0;

        // Collect IronBrew-style variables: [lI]{4,}
        const ironVars = new Set();
        const varPattern = /\b([lI]{4,})\b/g;
        let m;
        while ((m = varPattern.exec(code)) !== null) {
            if (m[1].length >= 4 && /[l]/.test(m[1]) && /[I]/.test(m[1])) {
                ironVars.add(m[1]);
            }
        }

        // Also collect _0x... dan other obfuscated names
        const otherPatterns = [
            /\b(_0x[0-9a-fA-F]+)\b/g,
            /\b([a-zA-Z_]*_[a-zA-Z_]*_[a-zA-Z_]*)\b/g,
        ];

        for (const pattern of otherPatterns) {
            while ((m = pattern.exec(code)) !== null) {
                if (m[1].length >= 3 && !this.isLuaKeyword(m[1])) {
                    ironVars.add(m[1]);
                }
            }
        }

        if (ironVars.size === 0) return { code: result, changed: false, changes: 0 };

        const renameMap = {};
        let counter = 1;
        for (const v of ironVars) {
            renameMap[v] = `v${counter++}`;
        }

        for (const [oldName, newName] of Object.entries(renameMap)) {
            const re = new RegExp(`\\b${oldName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'g');
            result = result.replace(re, newName);
            changes++;
        }

        return { code: result, changed: result !== code, changes, notes: `Renamed ${changes} variables` };
    }

    isLuaKeyword(name) {
        const keywords = new Set([
            'and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for',
            'function', 'if', 'in', 'local', 'nil', 'not', 'or', 'repeat',
            'return', 'then', 'true', 'until', 'while', 'continue',
        ]);
        return keywords.has(name);
    }

    // --- LEVEL 5: Control Flow Unflattening ---
    level5CFFUnflattening(code) {
        let result = code;
        let changes = 0;

        const cffPattern = /local\s+(v\d+|[a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*(0x[0-9a-fA-F]+|\d+)([\s\S]*?while\s+true\s+do[\s\S]*?end)/;
        const cffMatch = result.match(cffPattern);

        if (cffMatch) {
            const stateVar = cffMatch[1];
            const loopBody = cffMatch[3];

            const branchRegex = new RegExp(`(?:if|elseif)\\s+${stateVar}\\s*==\\s*(0x[0-9a-fA-F]+|\\d+)\\s*then([\\s\\S]*?)(?=(?:elseif|else|end))`, 'g');
            const branches = [];
            let bm;
            while ((bm = branchRegex.exec(loopBody)) !== null) {
                branches.push({ state: bm[1], body: bm[2].trim() });
            }

            if (branches.length >= 2) {
                branches.sort((a, b) => parseInt(a.state, 16) - parseInt(b.state, 16));
                let reconstructed = branches.map(b => {
                    return b.body
                        .replace(new RegExp(`${stateVar}\\s*=\\s*(0x[0-9a-fA-F]+|\\d+)\\s*`), '')
                        .replace(/break\s*/g, '')
                        .trim();
                }).filter(b => b.length > 0).join('\n');

                result = result.replace(cffMatch[0], reconstructed);
                changes++;
            }
        }

        return { code: result, changed: result !== code, changes, notes: changes > 0 ? 'Unflattened control flow' : null };
    }

    // --- LEVEL 6: VM Metadata Extraction ---
    level6VMMetadataExtraction(code) {
        let result = code;
        let changes = 0;
        const notes = [];

        const dispatchPattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{([\s\S]*?)\}/;
        const dispatchMatch = result.match(dispatchPattern);

        if (dispatchMatch) {
            const tableName = dispatchMatch[1];
            const tableBody = dispatchMatch[2];
            const funcEntries = (tableBody.match(/function/g) || []).length;

            if (funcEntries >= 5) {
                notes.push(`VM dispatch table: ${tableName} (${funcEntries} opcodes)`);

                const bytecodePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{\s*([\d\s,]+)\s*\}/;
                const bytecodeMatch = result.match(bytecodePattern);

                if (bytecodeMatch) {
                    const bytecodeName = bytecodeMatch[1];
                    const bytecode = bytecodeMatch[2].split(',').map(s => parseInt(s.trim(), 10)).filter(n => !isNaN(n));
                    notes.push(`Bytecode: ${bytecodeName} (${bytecode.length} ops)`);

                    const vmLoopPattern = /while\s+true\s+do[\s\S]*?break[\s\S]*?end/;
                    if (vmLoopPattern.test(result)) {
                        result = result.replace(vmLoopPattern,
                            `-- [[ VM LOOP EXTRACTED BY KAIRO ]]\n-- Bytecode: [${bytecode.slice(0, 30).join(', ')}${bytecode.length > 30 ? ', ...' : ''}]\n-- Opcodes: ${funcEntries}\n-- Full VM emulation required`);
                        changes++;
                    }
                }
            }
        }

        return { code: result, changed: result !== code, changes, notes: notes.length > 0 ? notes.join(' | ') : null };
    }

    // --- LEVEL 7: Anti-Tamper Bypass ---
    level7AntiTamperBypass(code) {
        let result = code;
        let changes = 0;

        // Detect integrity check function dan replace dengan return true
        const integrityPattern = /function\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\(\s*\)[\s\S]{100,}?return\s+(true|false)\s*end/g;
        result = result.replace(integrityPattern, (match, funcName) => {
            changes++;
            return `function ${funcName}() return true end -- [[ ANTI-TAMPER BYPASSED BY KAIRO ]]`;
        });

        // Remove anti-debug checks
        const antiDebugPattern = /if\s+debug\.info\([^)]+\)\s*then\s*error\([^)]*\)\s*end/g;
        result = result.replace(antiDebugPattern, (match) => {
            changes++;
            return `-- [[ ANTI-DEBUG REMOVED BY KAIRO ]]`;
        });

        // Remove environment checks
        const envCheckPattern = /if\s+_G\[["'][^"']+["']\]\s*then\s*error\([^)]*\)\s*end/g;
        result = result.replace(envCheckPattern, (match) => {
            changes++;
            return `-- [[ ENV CHECK REMOVED BY KAIRO ]]`;
        });

        return { code: result, changed: result !== code, changes, notes: changes > 0 ? `Bypassed ${changes} anti-tamper checks` : null };
    }

    calculateEntropy(str) {
        if (!str || str.length === 0) return 0;
        const freq = {};
        for (const c of str) freq[c] = (freq[c] || 0) + 1;
        let entropy = 0;
        const len = str.length;
        for (const c in freq) {
            const p = freq[c] / len;
            if (p > 0) entropy -= p * Math.log2(p);
        }
        return entropy;
    }

    isClean(code) {
        const hasIronVars = /\b[lI]{4,}\b/.test(code);
        const hasHexVars = /_0x[0-9a-fA-F]{4,}/.test(code);
        const entropy = this.calculateEntropy(code);
        const hasDispatcher = /while\s+true\s+do[\s\S]{200,}if.*==.*then/.test(code);
        return !hasIronVars && !hasHexVars && entropy < 4.0 && !hasDispatcher;
    }
}


