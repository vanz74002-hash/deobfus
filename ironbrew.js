export function processIronBrew(code) {
    const detector = new IronBrewDetector();
    const detection = detector.detect(code);

    if (!detection.isIronBrew) {
        return {
            success: false,
            detection,
            deobfuscation: null,
            message: 'Input tidak terdeteksi sebagai IronBrew obfuscator',
        };
    }

    const deobfuscator = new IronBrewDeobfuscator();
    const deobfuscation = deobfuscator.deobfuscate(code, detection);

    return {
        success: deobfuscation.success,
        detection,
        deobfuscation,
        message: deobfuscation.success
            ? `Deobfuscation selesai. Version: ${detection.version}. Applied: ${deobfuscation.appliedLevels.map(l => l.level).join(', ')}`
            : 'Detect sebagai IronBrew tapi deobfuscation tidak menghasilkan perubahan signifikan',
    };
}
