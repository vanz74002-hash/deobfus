export function processBoronide(code) {
    const detector = new BoronideDetector();
    const detection = detector.detect(code);

    if (!detection.isBoronide) {
        return {
            success: false,
            detection,
            deobfuscation: null,
            message: 'Input tidak terdeteksi sebagai Boronide obfuscator',
        };
    }

    const deobfuscator = new BoronideDeobfuscator();
    const deobfuscation = deobfuscator.deobfuscate(code, detection);

    return {
        success: deobfuscation.success,
        detection,
        deobfuscation,
        message: deobfuscation.success
            ? `Deobfuscation selesai. Version: ${detection.version}. Applied: ${deobfuscation.appliedLevels.map(l => l.level).join(', ')}`
            : 'Detect sebagai Boronide tapi deobfuscation tidak menghasilkan perubahan signifikan',
    };
}
