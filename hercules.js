/**
 * KAIRO ENGINE // Hercules Obfuscator Detector & Deobfuscator
 * Target: Luau scripts obfuscated by Hercules
 * Signature: closure wrapping, _G/_ENV manipulation, custom cipher, VM-based (v2+)
 */

// ============================================================
// SECTION 1: DETECTION ENGINE
// ============================================================

export class HerculesDetector {
    constructor() {
        this.layers = [
            { name: 'SignatureScan', weight: 0.25, run: this.signatureScan.bind(this) },
            { name: 'ClosureWrappingPattern', weight: 0.25, run: this.closureWrappingPattern.bind(this) },
            { name: 'EnvironmentManipulation', weight: 0.15, run: this.environmentManipulation.bind(this) },
            { name: 'VMStructureDetection', weight: 0.15, run: this.vmStructureDetection.bind(this) },
            { name: 'StringEncryptionPattern', weight: 0.10, run: this.stringEncryptionPattern.bind(this) },
            { name: 'HeuristicAnalysis', weight: 0.10, run: this.heuristicAnalysis.bind(this) },
        ];
    }

    detect(code) {
        if (!code || typeof code !== 'string') {
            return { isHercules: false, confidence: 0, version: 'unknown', layers: [], error: 'Empty input' };
        }

        const results = [];
        let totalConfidence = 0;

        for (const layer of this.layers) {
            try {
                const layerResult = layer.run(code);
                results.push({
                    layer: layer.name,
                    confidence: layerResult.confidence,
                    evidence: layerResult.evidence || [],
                    versionHint: layerResult.versionHint || null,
                });
                totalConfidence += layerResult.confidence * layer.weight;
            } catch (err) {
                results.push({ layer: layer.name, confidence: 0, error: err.message });
            }
        }

        const isHercules = totalConfidence >= 0.50;
        const version = this.inferVersion(results, code);

        return {
            isHercules,
            confidence: Math.min(totalConfidence, 1.0),
            version,
            layers: results,
        };
    }

    // --- Layer 1: Signature / Watermark ---
    signatureScan(code) {
        const evidence = [];
        let confidence = 0;

        const signatures = [
            { pattern: /hercules/i, label: 'Hercules keyword' },
            { pattern: /hercules[_-]?obfuscator/i, label: 'Hercules obfuscator tag' },
            { pattern: /--\s*\[\[\s*Hercules/i, label: 'Hercules header comment' },
            { pattern: /HERCULES_V[0-9]/i, label: 'Version tag' },
            { pattern: /Generated by Hercules/i, label: 'Generator signature' },
            { pattern: /Hercules\s+Obfuscator/i, label: 'Hercules obfuscator comment' },
        ];

        for (const sig of signatures) {
            if (sig.pattern.test(code)) {
                evidence.push(sig.label);
                confidence += 0.20;
            }
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 2: Closure Wrapping Pattern (KHAS HERCULES) ---
    closureWrappingPattern(code) {
        const evidence = [];
        let confidence = 0;

        // Hercules signature: nested closure wrapping
        // Pattern: function() return function() ... end end
        const closureWrap = /function\s*\(\s*\)\s*return\s+function\s*\(\s*\)/g;
        const closureMatches = code.match(closureWrap);
        if (closureMatches && closureMatches.length >= 3) {
            evidence.push(`Closure wrapping: ${closureMatches.length} layers`);
            confidence += 0.40;
        } else if (closureMatches && closureMatches.length >= 1) {
            evidence.push(`Closure wrapping: ${closureMatches.length} layers`);
            confidence += 0.20;
        }

        // IIFE pattern: (function() ... end)()
        const iifePattern = /\(\s*function\s*\([^)]*\)[\s\S]*?end\s*\)\s*\(\s*\)/g;
        const iifeMatches = code.match(iifePattern);
        if (iifeMatches && iifeMatches.length >= 2) {
            evidence.push(`IIFE patterns: ${iifeMatches.length}`);
            confidence += 0.25;
        }

        // Return function pattern: return function(...) ... end
        const returnFuncPattern = /return\s+function\s*\([^)]*\)[\s\S]*?end/g;
        const returnFuncMatches = code.match(returnFuncPattern);
        if (returnFuncMatches && returnFuncMatches.length >= 3) {
            evidence.push(`Return function patterns: ${returnFuncMatches.length}`);
            confidence += 0.20;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 3: Environment Manipulation ---
    environmentManipulation(code) {
        const evidence = [];
        let confidence = 0;

        // _G manipulation
        const gManipPattern = /_G\[["'][^"']+["']\]\s*=/g;
        const gMatches = code.match(gManipPattern);
        if (gMatches && gMatches.length >= 3) {
            evidence.push(`_G manipulation: ${gMatches.length}`);
            confidence += 0.30;
        }

        // _ENV manipulation
        const envManipPattern = /_ENV\[["'][^"']+["']\]\s*=/g;
        const envMatches = code.match(envManipPattern);
        if (envMatches && envMatches.length >= 2) {
            evidence.push(`_ENV manipulation: ${envMatches.length}`);
            confidence += 0.25;
        }

        // setfenv/getfenv
        const fenvPattern = /setfenv|getfenv/g;
        const fenvMatches = code.match(fenvPattern);
        if (fenvMatches && fenvMatches.length >= 2) {
            evidence.push(`setfenv/getfenv usage: ${fenvMatches.length}`);
            confidence += 0.20;
        }

        // Environment sandboxing: local env = {} ... setfenv(func, env)
        const sandboxPattern = /local\s+[a-zA-Z_][a-zA-Z0-9_]*\s*=\s*\{\}[\s\S]*?setfenv\s*\(\s*[a-zA-Z_][a-zA-Z0-9_]*\s*,/g;
        if (sandboxPattern.test(code)) {
            evidence.push('Environment sandboxing detected');
            confidence += 0.20;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 4: VM Structure Detection (Hercules v2+) ---
    vmStructureDetection(code) {
        const evidence = [];
        let confidence = 0;

        // VM dispatch table
        const dispatchPattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{[\s\S]*?\[\d+\]\s*=\s*function/g;
        const dispatchMatches = code.match(dispatchPattern);
        if (dispatchMatches && dispatchMatches.length >= 5) {
            evidence.push(`VM dispatch table: ${dispatchMatches.length} opcodes`);
            confidence += 0.35;
        }

        // Bytecode array
        const bytecodePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{\s*[\d\s,]{80,}\s*\}/;
        if (bytecodePattern.test(code)) {
            evidence.push('Bytecode array detected');
            confidence += 0.20;
        }

        // VM loop
        const vmLoopPattern = /while\s+true\s+do[\s\S]{300,}if\s+[a-zA-Z_][a-zA-Z0-9_]*\s*==\s*\d+/;
        if (vmLoopPattern.test(code)) {
            evidence.push('VM dispatch loop detected');
            confidence += 0.20;
        }

        // Stack operations
        const stackPattern = /table\.insert\([^,]+,\s*[^)]+\)|table\.remove\([^)]+\)/g;
        const stackMatches = code.match(stackPattern);
        if (stackMatches && stackMatches.length >= 8) {
            evidence.push(`Stack operations: ${stackMatches.length}`);
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence, versionHint: confidence > 0.4 ? 'v2-vm' : null };
    }

    // --- Layer 5: String Encryption Pattern ---
    stringEncryptionPattern(code) {
        const evidence = [];
        let confidence = 0;

        // Custom cipher (bukan cuma XOR)
        // Pattern: string.char(byte - N) atau string.char(byte + N)
        const addSubPattern = /string\.char\s*\(\s*\d+\s*[+\-]\s*\d+\s*\)/g;
        const addSubMatches = code.match(addSubPattern);
        if (addSubMatches && addSubMatches.length >= 5) {
            evidence.push(`Add/subtract cipher: ${addSubMatches.length}`);
            confidence += 0.25;
        }

        // Multi-operation cipher: string.char(bit32.bxor(byte, key) + offset)
        const multiOpPattern = /string\.char\s*\([^)]*bit32\.[^)]*[+\-][^)]*\)/g;
        const multiOpMatches = code.match(multiOpPattern);
        if (multiOpMatches && multiOpMatches.length >= 3) {
            evidence.push(`Multi-operation cipher: ${multiOpMatches.length}`);
            confidence += 0.25;
        }

        // Decrypt function dengan custom logic
        const decryptFuncPattern = /function\s+[a-zA-Z_][a-zA-Z0-9_]*\s*\([^)]*\)[\s\S]{100,}return\s+string\.char/g;
        if (decryptFuncPattern.test(code)) {
            evidence.push('Custom decrypt function detected');
            confidence += 0.20;
        }

        // String table dengan encrypted entries
        const stringTablePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{\s*"[^"]{10,}"[\s\S]*?\}/;
        if (stringTablePattern.test(code)) {
            evidence.push('Encrypted string table');
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 6: Heuristic Analysis ---
    heuristicAnalysis(code) {
        const evidence = [];
        let confidence = 0;

        // High entropy strings
        const stringLiterals = code.match(/"([^"\\]|\\.)*"/g) || [];
        let highEntropyStrings = 0;
        for (const s of stringLiterals) {
            if (this.calculateEntropy(s) > 4.5 && s.length > 20) {
                highEntropyStrings++;
            }
        }
        if (highEntropyStrings > 5) {
            evidence.push(`High-entropy strings: ${highEntropyStrings}`);
            confidence += 0.25;
        }

        // Minified structure
        const lines = code.split('\n').filter(l => l.trim().length > 0);
        const avgLineLength = code.length / Math.max(lines.length, 1);
        if (avgLineLength > 5000 && lines.length < 10) {
            evidence.push(`Minified: ${lines.length} lines, avg ${avgLineLength.toFixed(0)} chars/line`);
            confidence += 0.20;
        }

        // Function density (Hercules punya banyak closure)
        const functionCount = (code.match(/\bfunction\b/g) || []).length;
        const localCount = (code.match(/\blocal\b/g) || []).length;
        if (localCount > 0 && functionCount / localCount > 0.4) {
            evidence.push(`High function/local ratio: ${(functionCount / localCount).toFixed(2)}`);
            confidence += 0.20;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    calculateEntropy(str) {
        if (!str || str.length === 0) return 0;
        const freq = {};
        for (const c of str) freq[c] = (freq[c] || 0) + 1;
        let entropy = 0;
        const len = str.length;
        for (const c in freq) {
            const p = freq[c] / len;
            if (p > 0) entropy -= p * Math.log2(p);
        }
        return entropy;
    }

    inferVersion(results, code) {
        const vm = results.find(r => r.layer === 'VMStructureDetection');
        const closure = results.find(r => r.layer === 'ClosureWrappingPattern');

        if (vm && vm.confidence > 0.5) {
            return 'v2-vm';
        }
        if (closure && closure.confidence > 0.4) {
            return 'v1-closure';
        }
        if (results.some(r => r.confidence > 0 && r.layer === 'SignatureScan')) {
            return 'v1-legacy';
        }
        return 'unknown';
    }
}


// ============================================================
// SECTION 2: DEOBFUSCATION ENGINE
// ============================================================

export class HerculesDeobfuscator {
    constructor() {
        this.levels = [
            { name: 'BasicCleanup', run: this.level1BasicCleanup.bind(this) },
            { name: 'ClosureUnwrapping', run: this.level2ClosureUnwrapping.bind(this) },
            { name: 'StringDecryption', run: this.level3StringDecryption.bind(this) },
            { name: 'EnvironmentRestoration', run: this.level4EnvironmentRestoration.bind(this) },
            { name: 'VariableRenaming', run: this.level5VariableRenaming.bind(this) },
            { name: 'ControlFlowUnflattening', run: this.level6CFFUnflattening.bind(this) },
            { name: 'VMMetadataExtraction', run: this.level7VMMetadataExtraction.bind(this) },
        ];
    }

    deobfuscate(code, detectionResult = null) {
        if (!code) return { success: false, deobfuscatedCode: '', appliedLevels: [], notes: 'Empty input' };

        let current = code;
        const appliedLevels = [];
        const notes = [];

        const orderedLevels = this.orderLevelsByHint(detectionResult);

        for (const level of orderedLevels) {
            try {
                const before = current;
                const result = level.run(current);

                if (result.changed && result.code !== before) {
                    current = result.code;
                    appliedLevels.push({
                        level: level.name,
                        changes: result.changes || 0,
                        notes: result.notes || null,
                    });

                    if (this.isClean(current)) {
                        notes.push(`Early exit after ${level.name}`);
                        break;
                    }
                }
            } catch (err) {
                notes.push(`${level.name} failed: ${err.message}`);
            }
        }

        return {
            success: appliedLevels.length > 0,
            deobfuscatedCode: current,
            appliedLevels,
            notes: notes.join(' | '),
            finalEntropy: this.calculateEntropy(current),
        };
    }

    orderLevelsByHint(detection) {
        if (!detection || !detection.version) return this.levels;

        const v = detection.version;
        if (v === 'v2-vm') {
            return [
                this.levels[1], // Closure
                this.levels[2], // String
                this.levels[6], // VM
                this.levels[0], // Cleanup
                this.levels[3], // Environment
                this.levels[4], // Rename
                this.levels[5], // CFF
            ];
        }
        if (v === 'v1-closure' || v === 'v1-legacy') {
            return [
                this.levels[1], // Closure
                this.levels[2], // String
                this.levels[3], // Environment
                this.levels[0], // Cleanup
                this.levels[4], // Rename
                this.levels[5], // CFF
                this.levels[6], // VM
            ];
        }
        return this.levels;
    }

    // --- LEVEL 1: Basic Cleanup ---
    level1BasicCleanup(code) {
        let result = code;
        let changes = 0;

        // Hapus watermark Hercules
        const before = result;
        result = result.replace(/--\s*\[\[\s*Hercules[\s\S]*?\]\]/gi, '');
        result = result.replace(/--\s*Generated by Hercules.*/gi, '');
        result = result.replace(/--\s*Hercules\s+Obfuscator.*/gi, '');
        if (result !== before) changes++;

        // Hapus komentar kosong beruntun
        result = result.replace(/(--[^\n]*\n){3,}/g, '--\n');

        // Opaque predicate sederhana
        const opaquePattern = /if\s+\(([^)]{10,})\)\s*then\s*([\s\S]*?)\s*end/g;
        result = result.replace(opaquePattern, (match, cond, body) => {
            if (/^\s*\(?[a-zA-Z_0-9]+\s*==\s*\1\)?\s*$/.test(cond) || /^\s*\(?\s*0\s*==\s*0\s*\)?\s*$/.test(cond)) {
                changes++;
                return body.trim();
            }
            return match;
        });

        return { code: result, changed: result !== code, changes };
    }

    // --- LEVEL 2: Closure Unwrapping (KUNCI HERCULES) ---
    level2ClosureUnwrapping(code) {
        let result = code;
        let changes = 0;

        // Pattern: (function() return function() ... end end)()
        // Unwrap ke: function() ... end
        const closureWrapPattern = /\(\s*function\s*\(\s*\)\s*return\s+([\s\S]*?)\s*end\s*end\s*\)\s*\(\s*\)/g;
        result = result.replace(closureWrapPattern, (match, inner) => {
            changes++;
            return inner.trim();
        });

        // Pattern: function() return function(...) ... end end
        const returnClosurePattern = /function\s*\(\s*\)\s*return\s+function\s*\(([^)]*)\)([\s\S]*?)end\s*end/g;
        result = result.replace(returnClosurePattern, (match, params, body) => {
            changes++;
            return `function(${params})${body}end`;
        });

        // IIFE: (function() ... end)() → inline body
        const iifePattern = /\(\s*function\s*\([^)]*\)([\s\S]*?)end\s*\)\s*\(\s*\)/g;
        result = result.replace(iifePattern, (match, body) => {
            // Cek apakah body cuma return statement
            const returnMatch = body.match(/^\s*return\s+([\s\S]+?)\s*$/);
            if (returnMatch) {
                changes++;
                return returnMatch[1].trim();
            }
            return match;
        });

        // Iterasi sampai stabil (nested closure)
        let prevResult = '';
        let iterations = 0;
        while (prevResult !== result && iterations < 5) {
            prevResult = result;
            result = result.replace(/\(\s*function\s*\(\s*\)\s*return\s+([\s\S]*?)\s*end\s*end\s*\)\s*\(\s*\)/g, (match, inner) => {
                changes++;
                return inner.trim();
            });
            iterations++;
        }

        return { code: result, changed: result !== code, changes, notes: changes > 0 ? `Unwrapped ${changes} closures` : null };
    }

    // --- LEVEL 3: String Decryption ---
    level3StringDecryption(code) {
        let result = code;
        let changes = 0;

        // Pattern 1: string.char(a, b, c) langsung
        result = result.replace(/string\.char\(([\d\s,]+)\)/g, (match, args) => {
            try {
                const bytes = args.split(',').map(s => parseInt(s.trim(), 10));
                if (bytes.every(n => !isNaN(n) && n >= 0 && n <= 255)) {
                    changes++;
                    return JSON.stringify(String.fromCharCode(...bytes));
                }
            } catch (e) { /* ignore */ }
            return match;
        });

        // Pattern 2: Add/subtract cipher: string.char(N - K) atau string.char(N + K)
        result = result.replace(/string\.char\s*\(\s*(\d+)\s*([+\-])\s*(\d+)\s*\)/g, (match, a, op, b) => {
            const na = parseInt(a, 10);
            const nb = parseInt(b, 10);
            let r = op === '+' ? na + nb : na - nb;
            if (r >= 0 && r <= 255) {
                changes++;
                return JSON.stringify(String.fromCharCode(r));
            }
            return match;
        });

        // Pattern 3: Multi-operation: string.char(bit32.bxor(N, K) + offset)
        result = result.replace(/string\.char\s*\(\s*bit32\.bxor\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)\s*([+\-])\s*(\d+)\s*\)/g, (match, a, k, op, offset) => {
            const xorResult = parseInt(a, 10) ^ parseInt(k, 10);
            const final = op === '+' ? xorResult + parseInt(offset, 10) : xorResult - parseInt(offset, 10);
            if (final >= 0 && final <= 255) {
                changes++;
                return JSON.stringify(String.fromCharCode(final));
            }
            return match;
        });

        // Pattern 4: XOR dengan key recovery
        const keyPatterns = [
            /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*(\d+)\s*(?:--\s*key)?/i,
        ];

        let recoveredKey = null;
        let keyName = null;
        for (const kp of keyPatterns) {
            const km = code.match(kp);
            if (km) {
                const candidate = parseInt(km[2], 10);
                if (candidate >= 0 && candidate <= 255) {
                    recoveredKey = candidate;
                    keyName = km[1];
                    break;
                }
            }
        }

        if (recoveredKey !== null) {
            const xorCharPattern = /string\.char\(\s*((?:bit32\.bxor\(\s*\d+\s*,\s*[a-zA-Z_][a-zA-Z0-9_]*\s*\)\s*,?\s*)+)\)/g;
            result = result.replace(xorCharPattern, (match, inner) => {
                try {
                    const byteMatches = [...inner.matchAll(/bit32\.bxor\(\s*(\d+)\s*,\s*([a-zA-Z_][a-zA-Z0-9_]*)\s*\)/g)];
                    const bytes = byteMatches.map(m => {
                        const byte = parseInt(m[1], 10);
                        const varKey = m[2];
                        if (varKey === keyName) return byte ^ recoveredKey;
                        return byte;
                    });
                    if (bytes.length > 0 && bytes.every(n => n >= 0 && n <= 255)) {
                        changes++;
                        return JSON.stringify(String.fromCharCode(...bytes));
                    }
                } catch (e) { /* ignore */ }
                return match;
            });
        }

        // Pattern 5: String table lookup
        const tablePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{([^}]+)\}/;
        const tableMatch = result.match(tablePattern);
        if (tableMatch) {
            const tableName = tableMatch[1];
            const entries = tableMatch[2].split(',').map(s => {
                const trimmed = s.trim();
                if (/^["'].*["']$/.test(trimmed)) {
                    try { return JSON.parse(trimmed); } catch (e) { return null; }
                }
                const n = parseInt(trimmed, 10);
                return isNaN(n) ? null : n;
            });

            const lookupPattern = new RegExp(`${tableName}\\[(\\d+)\\]`, 'g');
            result = result.replace(lookupPattern, (match, idx) => {
                const i = parseInt(idx, 10);
                if (entries[i] !== null && entries[i] !== undefined) {
                    changes++;
                    return typeof entries[i] === 'string' ? JSON.stringify(entries[i]) : entries[i];
                }
                return match;
            });
        }

        return { code: result, changed: result !== code, changes, notes: changes > 0 ? `Decrypted ${changes} strings` : null };
    }

    // --- LEVEL 4: Environment Restoration ---
    level4EnvironmentRestoration(code) {
        let result = code;
        let changes = 0;

        // Detect _G manipulation dan restore
        // Pattern: _G["funcName"] = function(...) ... end
        // Replace dengan: local funcName = function(...) ... end
        const gAssignPattern = /_G\[["']([^"']+)["']\]\s*=\s*function\s*\(([^)]*)\)([\s\S]*?)end/g;
        result = result.replace(gAssignPattern, (match, funcName, params, body) => {
            changes++;
            return `local ${funcName} = function(${params})${body}end`;
        });

        // Detect _ENV manipulation
        const envAssignPattern = /_ENV\[["']([^"']+)["']\]\s*=\s*function\s*\(([^)]*)\)([\s\S]*?)end/g;
        result = result.replace(envAssignPattern, (match, funcName, params, body) => {
            changes++;
            return `local ${funcName} = function(${params})${body}end`;
        });

        // Remove setfenv/getfenv calls yang nggak perlu
        result = result.replace(/setfenv\s*\(\s*[a-zA-Z_][a-zA-Z0-9_]*\s*,\s*_G\s*\)/g, (match) => {
            changes++;
            return `-- [[ setfenv removed by Kairo ]]`;
        });

        return { code: result, changed: result !== code, changes, notes: changes > 0 ? `Restored ${changes} environment manipulations` : null };
    }

    // --- LEVEL 5: Variable Renaming ---
    level5VariableRenaming(code) {
        let result = code;
        let changes = 0;

        // Collect obfuscated variables
        const obfVars = new Set();
        const varPatterns = [
            /\b(_0x[0-9a-fA-F]+)\b/g,
            /\b([a-zA-Z_][a-zA-Z0-9_]{1,3})\b/g, // Short variable names
        ];

        for (const pattern of varPatterns) {
            let m;
            while ((m = pattern.exec(code)) !== null) {
                if (m[1].length >= 2 && !this.isLuaKeyword(m[1])) {
                    obfVars.add(m[1]);
                }
            }
        }

        if (obfVars.size === 0) return { code: result, changed: false, changes: 0 };

        const renameMap = {};
        let counter = 1;
        for (const v of obfVars) {
            renameMap[v] = `v${counter++}`;
        }

        for (const [oldName, newName] of Object.entries(renameMap)) {
            const re = new RegExp(`\\b${oldName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'g');
            result = result.replace(re, newName);
            changes++;
        }

        return { code: result, changed: result !== code, changes, notes: `Renamed ${changes} variables` };
    }

    isLuaKeyword(name) {
        const keywords = new Set([
            'and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for',
            'function', 'if', 'in', 'local', 'nil', 'not', 'or', 'repeat',
            'return', 'then', 'true', 'until', 'while', 'continue',
        ]);
        return keywords.has(name);
    }

    // --- LEVEL 6: Control Flow Unflattening ---
    level6CFFUnflattening(code) {
        let result = code;
        let changes = 0;

        const cffPattern = /local\s+(v\d+|[a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*(0x[0-9a-fA-F]+|\d+)([\s\S]*?while\s+true\s+do[\s\S]*?end)/;
        const cffMatch = result.match(cffPattern);

        if (cffMatch) {
            const stateVar = cffMatch[1];
            const loopBody = cffMatch[3];

            const branchRegex = new RegExp(`(?:if|elseif)\\s+${stateVar}\\s*==\\s*(0x[0-9a-fA-F]+|\\d+)\\s*then([\\s\\S]*?)(?=(?:elseif|else|end))`, 'g');
            const branches = [];
            let bm;
            while ((bm = branchRegex.exec(loopBody)) !== null) {
                branches.push({ state: bm[1], body: bm[2].trim() });
            }

            if (branches.length >= 2) {
                branches.sort((a, b) => parseInt(a.state, 16) - parseInt(b.state, 16));
                let reconstructed = branches.map(b => {
                    return b.body
                        .replace(new RegExp(`${stateVar}\\s*=\\s*(0x[0-9a-fA-F]+|\\d+)\\s*`), '')
                        .replace(/break\s*/g, '')
                        .trim();
                }).filter(b => b.length > 0).join('\n');

                result = result.replace(cffMatch[0], reconstructed);
                changes++;
            }
        }

        return { code: result, changed: result !== code, changes, notes: changes > 0 ? 'Unflattened control flow' : null };
    }

    // --- LEVEL 7: VM Metadata Extraction ---
    level7VMMetadataExtraction(code) {
        let result = code;
        let changes = 0;
        const notes = [];

        const dispatchPattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{([\s\S]*?)\}/;
        const dispatchMatch = result.match(dispatchPattern);

        if (dispatchMatch) {
            const tableName = dispatchMatch[1];
            const tableBody = dispatchMatch[2];
            const funcEntries = (tableBody.match(/function/g) || []).length;

            if (funcEntries >= 5) {
                notes.push(`VM dispatch table: ${tableName} (${funcEntries} opcodes)`);

                const bytecodePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{\s*([\d\s,]+)\s*\}/;
                const bytecodeMatch = result.match(bytecodePattern);

                if (bytecodeMatch) {
                    const bytecodeName = bytecodeMatch[1];
                    const bytecode = bytecodeMatch[2].split(',').map(s => parseInt(s.trim(), 10)).filter(n => !isNaN(n));
                    notes.push(`Bytecode: ${bytecodeName} (${bytecode.length} ops)`);

                    const vmLoopPattern = /while\s+true\s+do[\s\S]*?break[\s\S]*?end/;
                    if (vmLoopPattern.test(result)) {
                        result = result.replace(vmLoopPattern,
                            `-- [[ VM LOOP EXTRACTED BY KAIRO ]]\n-- Bytecode: [${bytecode.slice(0, 30).join(', ')}${bytecode.length > 30 ? ', ...' : ''}]\n-- Opcodes: ${funcEntries}\n-- Full VM emulation required`);
                        changes++;
                    }
                }
            }
        }

        return { code: result, changed: result !== code, changes, notes: notes.length > 0 ? notes.join(' | ') : null };
    }

    calculateEntropy(str) {
        if (!str || str.length === 0) return 0;
        const freq = {};
        for (const c of str) freq[c] = (freq[c] || 0) + 1;
        let entropy = 0;
        const len = str.length;
        for (const c in freq) {
            const p = freq[c] / len;
            if (p > 0) entropy -= p * Math.log2(p);
        }
        return entropy;
    }

    isClean(code) {
        const hasHexVars = /_0x[0-9a-fA-F]{4,}/.test(code);
        const hasClosureWrap = /\(\s*function\s*\(\s*\)\s*return\s+function/.test(code);
        const entropy = this.calculateEntropy(code);
        const hasDispatcher = /while\s+true\s+do[\s\S]{200,}if.*==.*then/.test(code);
        return !hasHexVars && !hasClosureWrap && entropy < 4.0 && !hasDispatcher;
    }
}


