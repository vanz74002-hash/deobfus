export function processHercules(code) {
    const detector = new HerculesDetector();
    const detection = detector.detect(code);

    if (!detection.isHercules) {
        return {
            success: false,
            detection,
            deobfuscation: null,
            message: 'Input tidak terdeteksi sebagai Hercules obfuscator',
        };
    }

    const deobfuscator = new HerculesDeobfuscator();
    const deobfuscation = deobfuscator.deobfuscate(code, detection);

    return {
        success: deobfuscation.success,
        detection,
        deobfuscation,
        message: deobfuscation.success
            ? `Deobfuscation selesai. Version: ${detection.version}. Applied: ${deobfuscation.appliedLevels.map(l => l.level).join(', ')}`
            : 'Detect sebagai Hercules tapi deobfuscation tidak menghasilkan perubahan signifikan',
    };
}
