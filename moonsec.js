export function processMoonSec(code) {
    const detector = new MoonSecDetector();
    const detection = detector.detect(code);

    if (!detection.isMoonSec) {
        return {
            success: false,
            detection,
            deobfuscation: null,
            message: 'Input tidak terdeteksi sebagai MoonSec obfuscator',
        };
    }

    const deobfuscator = new MoonSecDeobfuscator();
    const deobfuscation = deobfuscator.deobfuscate(code, detection);

    return {
        success: deobfuscation.success,
        detection,
        deobfuscation,
        message: deobfuscation.success
            ? `Deobfuscation selesai. Version: ${detection.version}. Applied: ${deobfuscation.appliedLevels.map(l => l.level).join(', ')}`
            : 'Detect sebagai MoonSec tapi deobfuscation tidak menghasilkan perubahan signifikan',
    };
}
