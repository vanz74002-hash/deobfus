/**
 * KAIRO ENGINE // Luraph Obfuscator Detector & Deobfuscator
 * Target: Luau scripts obfuscated by Luraph (VM-based, string encryption, anti-tamper)
 */

// ============================================================
// SECTION 1: DETECTION ENGINE
// ============================================================

export class LuraphDetector {
    constructor() {
        this.layers = [
            { name: 'SignatureScan', weight: 0.35, run: this.signatureScan.bind(this) },
            { name: 'VMStructureDetection', weight: 0.30, run: this.vmStructureDetection.bind(this) },
            { name: 'StringEncryptionPattern', weight: 0.15, run: this.stringEncryptionPattern.bind(this) },
            { name: 'AntiTamperDetection', weight: 0.10, run: this.antiTamperDetection.bind(this) },
            { name: 'HeuristicAnalysis', weight: 0.10, run: this.heuristicAnalysis.bind(this) },
        ];
    }

    detect(code) {
        if (!code || typeof code !== 'string') {
            return { isLuraph: false, confidence: 0, version: 'unknown', layers: [], error: 'Empty input' };
        }

        const results = [];
        let totalConfidence = 0;

        for (const layer of this.layers) {
            try {
                const layerResult = layer.run(code);
                results.push({
                    layer: layer.name,
                    confidence: layerResult.confidence,
                    evidence: layerResult.evidence || [],
                    versionHint: layerResult.versionHint || null,
                });
                totalConfidence += layerResult.confidence * layer.weight;
            } catch (err) {
                results.push({ layer: layer.name, confidence: 0, error: err.message });
            }
        }

        const isLuraph = totalConfidence >= 0.50;
        const version = this.inferVersion(results, code);

        return {
            isLuraph,
            confidence: Math.min(totalConfidence, 1.0),
            version,
            layers: results,
        };
    }

    // --- Layer 1: Signature / Watermark ---
    signatureScan(code) {
        const evidence = [];
        let confidence = 0;

        const signatures = [
            { pattern: /luraph/i, label: 'Luraph keyword' },
            { pattern: /_luraph[_-]?/i, label: 'Luraph variable prefix' },
            { pattern: /--\s*\[\[\s*Luraph/i, label: 'Luraph header comment' },
            { pattern: /LURAPH_V[0-9]/i, label: 'Version tag' },
            { pattern: /Generated by Luraph/i, label: 'Generator signature' },
            { pattern: /luraph\.io/i, label: 'Luraph domain reference' },
        ];

        for (const sig of signatures) {
            if (sig.pattern.test(code)) {
                evidence.push(sig.label);
                confidence += 0.20;
            }
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 2: VM Structure Detection ---
    vmStructureDetection(code) {
        const evidence = [];
        let confidence = 0;

        // Luraph pakai stack-based VM: dispatch table + bytecode + stack operations
        // Pattern: local OPCODES = { [0] = function() ... end, ... }
        const dispatchPattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{[\s\S]*?\[\d+\]\s*=\s*function/g;
        const dispatchMatches = code.match(dispatchPattern);
        if (dispatchMatches && dispatchMatches.length >= 5) {
            evidence.push(`VM dispatch table: ${dispatchMatches.length} opcodes`);
            confidence += 0.35;
        }

        // Bytecode array: local BYTECODE = {0, 1, 2, ...}
        const bytecodePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{\s*[\d\s,]{50,}\s*\}/;
        if (bytecodePattern.test(code)) {
            evidence.push('Bytecode array detected');
            confidence += 0.20;
        }

        // Stack operations: push/pop pattern
        const stackPattern = /table\.insert\([^,]+,\s*[^)]+\)|table\.remove\([^)]+\)/g;
        const stackMatches = code.match(stackPattern);
        if (stackMatches && stackMatches.length >= 10) {
            evidence.push(`Stack operations: ${stackMatches.length}`);
            confidence += 0.15;
        }

        // VM loop: while true do ... if opcode == X then ... end
        const vmLoopPattern = /while\s+true\s+do[\s\S]{300,}if\s+[a-zA-Z_][a-zA-Z0-9_]*\s*==\s*\d+/;
        if (vmLoopPattern.test(code)) {
            evidence.push('VM dispatch loop detected');
            confidence += 0.20;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 3: String Encryption Pattern ---
    stringEncryptionPattern(code) {
        const evidence = [];
        let confidence = 0;

        // Luraph pakai XOR dengan key scheduling
        // Pattern: string.char(bit32.bxor(byte, key)) atau custom XOR function
        const xorPattern = /bit32\.bxor\s*\(\s*\d+\s*,\s*\d+\s*\)/g;
        const xorMatches = code.match(xorPattern);
        if (xorMatches && xorMatches.length >= 5) {
            evidence.push(`XOR operations: ${xorMatches.length}`);
            confidence += 0.25;
        }

        // String decryption function: function decrypt(encrypted, key) ... end
        const decryptFuncPattern = /function\s+[a-zA-Z_][a-zA-Z0-9_]*\s*\([^)]*encrypted[^)]*\)[\s\S]{100,}return\s+string\.char/g;
        if (decryptFuncPattern.test(code)) {
            evidence.push('String decryption function detected');
            confidence += 0.20;
        }

        // Encrypted string table: local STRINGS = {"...", "...", ...}
        const stringTablePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{\s*"[^"]{10,}"[\s\S]*?\}/;
        if (stringTablePattern.test(code)) {
            evidence.push('Encrypted string table detected');
            confidence += 0.15;
        }

        // Key scheduling: loop yang generate key dari seed
        const keySchedPattern = /for\s+[a-zA-Z_][a-zA-Z0-9_]*\s*=\s*\d+\s*,\s*\d+\s+do[\s\S]{50,}bit32\.bxor/g;
        if (keySchedPattern.test(code)) {
            evidence.push('Key scheduling loop detected');
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 4: Anti-Tamper Detection ---
    antiTamperDetection(code) {
        const evidence = [];
        let confidence = 0;

        // Anti-tamper: integrity check (hash bytecode/source)
        const integrityPattern = /function\s+[a-zA-Z_][a-zA-Z0-9_]*\s*\(\s*\)[\s\S]{100,}return\s+(true|false)/g;
        const integrityMatches = code.match(integrityPattern);
        if (integrityMatches && integrityMatches.length >= 2) {
            evidence.push(`Integrity check functions: ${integrityMatches.length}`);
            confidence += 0.25;
        }

        // Anti-debug: check debug.info, getfenv, setfenv
        const antiDebugPattern = /debug\.info|getfenv|setfenv|debug\.getinfo/g;
        const antiDebugMatches = code.match(antiDebugPattern);
        if (antiDebugMatches && antiDebugMatches.length >= 3) {
            evidence.push(`Anti-debug checks: ${antiDebugMatches.length}`);
            confidence += 0.20;
        }

        // Environment check: _G, _ENV manipulation
        const envCheckPattern = /_G\[["'][^"']+["']\]|_ENV\[["'][^"']+["']\]/g;
        const envMatches = code.match(envCheckPattern);
        if (envMatches && envMatches.length >= 2) {
            evidence.push(`Environment manipulation: ${envMatches.length}`);
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 5: Heuristic Analysis ---
    heuristicAnalysis(code) {
        const evidence = [];
        let confidence = 0;

        // Variable naming: Luraph kadang pakai pattern `_luraph_...` atau hex
        const varMatches = code.match(/local\s+([a-zA-Z_][a-zA-Z0-9_]*)/g) || [];
        const luraphVars = varMatches.filter(v => /_luraph|_0x[0-9a-fA-F]+/.test(v));
        const luraphRatio = varMatches.length > 0 ? luraphVars.length / varMatches.length : 0;

        if (luraphRatio > 0.5) {
            evidence.push(`Luraph-style variable ratio: ${(luraphRatio * 100).toFixed(1)}%`);
            confidence += 0.30;
        } else if (luraphRatio > 0.2) {
            evidence.push(`Luraph-style variable ratio: ${(luraphRatio * 100).toFixed(1)}%`);
            confidence += 0.15;
        }

        // High entropy strings
        const stringLiterals = code.match(/"([^"\\]|\\.)*"/g) || [];
        let highEntropyStrings = 0;
        for (const s of stringLiterals) {
            if (this.calculateEntropy(s) > 4.5 && s.length > 20) {
                highEntropyStrings++;
            }
        }
        if (highEntropyStrings > 5) {
            evidence.push(`High-entropy strings: ${highEntropyStrings}`);
            confidence += 0.20;
        }

        // Function count vs variable count (VM-heavy code punya banyak function)
        const functionCount = (code.match(/\bfunction\b/g) || []).length;
        const localCount = (code.match(/\blocal\b/g) || []).length;
        if (localCount > 0 && functionCount / localCount > 0.3) {
            evidence.push(`High function/local ratio: ${(functionCount / localCount).toFixed(2)}`);
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    calculateEntropy(str) {
        if (!str || str.length === 0) return 0;
        const freq = {};
        for (const c of str) freq[c] = (freq[c] || 0) + 1;
        let entropy = 0;
        const len = str.length;
        for (const c in freq) {
            const p = freq[c] / len;
            if (p > 0) entropy -= p * Math.log2(p);
        }
        return entropy;
    }

    inferVersion(results, code) {
        const vm = results.find(r => r.layer === 'VMStructureDetection');
        const antiTamper = results.find(r => r.layer === 'AntiTamperDetection');

        if (vm && vm.confidence > 0.6 && antiTamper && antiTamper.confidence > 0.3) {
            return 'v3-vm-antitamper';
        }
        if (vm && vm.confidence > 0.6) {
            return 'v2-vm';
        }
        if (results.some(r => r.confidence > 0 && r.layer === 'SignatureScan')) {
            return 'v1-legacy';
        }
        return 'unknown';
    }
}


