/**
 * KAIRO ENGINE // Prometheus Obfuscator Detector & Deobfuscator
 * Multi-layer detection + cascading deobfuscation
 * Target: Luau / Roblox scripts obfuscated by Prometheus (legacy → latest)
 */

// ============================================================
// SECTION 1: DETECTION ENGINE
// ============================================================

export class PrometheusDetector {
    constructor() {
        this.layers = [
            { name: 'SignatureScan', weight: 0.40, run: this.signatureScan.bind(this) },
            { name: 'PatternMatch', weight: 0.30, run: this.patternMatch.bind(this) },
            { name: 'HeuristicAnalysis', weight: 0.15, run: this.heuristicAnalysis.bind(this) },
            { name: 'StructuralAnalysis', weight: 0.15, run: this.structuralAnalysis.bind(this) },
        ];
    }

    /**
     * Main detection entry point. Returns confidence score + metadata.
     * Threshold: >= 0.55 = positif Prometheus
     */
    detect(code) {
        if (!code || typeof code !== 'string') {
            return { isPrometheus: false, confidence: 0, version: 'unknown', layers: [], error: 'Empty input' };
        }

        const results = [];
        let totalConfidence = 0;

        for (const layer of this.layers) {
            try {
                const layerResult = layer.run(code);
                results.push({
                    layer: layer.name,
                    confidence: layerResult.confidence,
                    evidence: layerResult.evidence || [],
                    versionHint: layerResult.versionHint || null,
                });
                totalConfidence += layerResult.confidence * layer.weight;
            } catch (err) {
                results.push({ layer: layer.name, confidence: 0, error: err.message });
            }
        }

        const isPrometheus = totalConfidence >= 0.55;
        const version = this.inferVersion(results, code);

        return {
            isPrometheus,
            confidence: Math.min(totalConfidence, 1.0),
            version,
            layers: results,
        };
    }

    // --- Layer 1: Signature / Watermark ---
    signatureScan(code) {
        const evidence = [];
        let confidence = 0;

        // Prometheus kadang ninggalin watermark di komentar atau string
        const signatures = [
            { pattern: /Prometheus/i, label: 'Prometheus keyword' },
            { pattern: /prometheus[_-]?obfuscator/i, label: 'Prometheus obfuscator tag' },
            { pattern: /--\s*\[\[\s*Prometheus/i, label: 'Prometheus header comment' },
            { pattern: /PROMETHEUS_V[0-9]/i, label: 'Version tag' },
            { pattern: /Generated by Prometheus/i, label: 'Generator signature' },
        ];

        for (const sig of signatures) {
            if (sig.pattern.test(code)) {
                evidence.push(sig.label);
                confidence += 0.25;
            }
        }

        return { confidence: Math.min(confidence, 1.0), evidence, versionHint: 'unknown' };
    }

    // --- Layer 2: Pattern Matching ---
    patternMatch(code) {
        const evidence = [];
        let confidence = 0;

        // Pattern khas Prometheus Luau
        const patterns = [
            // Variable naming _0x hex
            { pattern: /local\s+_0x[0-9a-fA-F]{4,}/g, label: 'Hex variable naming (_0x...)', weight: 0.15 },
            // String table pattern (array of encrypted strings)
            { pattern: /local\s+_0x[0-9a-fA-F]+\s*=\s*\{[^}]{50,}\}/s, label: 'String table array', weight: 0.20 },
            // XOR string decryption
            { pattern: /string\.char\(.*bit32\.bxor.*/g, label: 'XOR string decryption', weight: 0.20 },
            // string.char + byte manipulation
            { pattern: /string\.char\([^)]{30,}\)/g, label: 'Complex string.char call', weight: 0.10 },
            // Control flow state variable
            { pattern: /local\s+_0x[0-9a-fA-F]+\s*=\s*0x[0-9a-fA-F]+.*while\s+true/s, label: 'CFF state variable', weight: 0.15 },
            // Opaque predicate pattern
            { pattern: /if\s+\([^)]{20,}\)\s*then\s*(true|false|return)/g, label: 'Opaque predicate', weight: 0.10 },
        ];

        for (const p of patterns) {
            const matches = code.match(p.pattern);
            if (matches && matches.length > 0) {
                evidence.push(`${p.label} (${matches.length}x)`);
                confidence += p.weight * Math.min(matches.length / 3, 2);
            }
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 3: Heuristic Analysis ---
    heuristicAnalysis(code) {
        const evidence = [];
        let confidence = 0;

        // 3a. Variable name entropy — kalau kebanyakan _0x, tinggi
        const varMatches = code.match(/local\s+([a-zA-Z_][a-zA-Z0-9_]*)/g) || [];
        const hexVars = varMatches.filter(v => /_0x[0-9a-fA-F]+/.test(v));
        const hexRatio = varMatches.length > 0 ? hexVars.length / varMatches.length : 0;

        if (hexRatio > 0.6) {
            evidence.push(`Hex variable ratio: ${(hexRatio * 100).toFixed(1)}%`);
            confidence += 0.3;
        } else if (hexRatio > 0.3) {
            evidence.push(`Hex variable ratio: ${(hexRatio * 100).toFixed(1)}%`);
            confidence += 0.15;
        }

        // 3b. String entropy — encrypted string punya entropy tinggi
        const stringLiterals = code.match(/"([^"\\]|\\.)*"/g) || [];
        let highEntropyStrings = 0;
        for (const s of stringLiterals) {
            if (this.calculateEntropy(s) > 4.5 && s.length > 20) {
                highEntropyStrings++;
            }
        }
        if (highEntropyStrings > 5) {
            evidence.push(`High-entropy strings: ${highEntropyStrings}`);
            confidence += 0.25;
        }

        // 3c. Dead code ratio — banyak return sebelum akhir function
        const returnCount = (code.match(/\breturn\b/g) || []).length;
        const functionCount = (code.match(/\bfunction\b/g) || []).length;
        if (functionCount > 0 && returnCount / functionCount > 2.5) {
            evidence.push(`High return/function ratio: ${(returnCount / functionCount).toFixed(2)}`);
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 4: Structural Analysis ---
    structuralAnalysis(code) {
        const evidence = [];
        let confidence = 0;

        // 4a. VM interpreter detection — loop besar + dispatch table
        const vmPatterns = [
            /while\s+true\s+do[\s\S]{500,}if\s+_0x[0-9a-fA-F]+\s*==/i,
            /local\s+_0x[0-9a-fA-F]+\s*=\s*\{[\s\S]{200,}\}[\s\S]*while\s+true/,
        ];
        for (const p of vmPatterns) {
            if (p.test(code)) {
                evidence.push('VM interpreter structure detected');
                confidence += 0.4;
                break;
            }
        }

        // 4b. Proxy function pattern — function wrapper yang cuma return/forward
        const proxyPattern = /function\s+_0x[0-9a-fA-F]+\s*\([^)]*\)\s*return\s+_0x[0-9a-fA-F]+\s*\(/g;
        const proxyMatches = code.match(proxyPattern);
        if (proxyMatches && proxyMatches.length > 3) {
            evidence.push(`Proxy functions: ${proxyMatches.length}`);
            confidence += 0.25;
        }

        // 4c. Dispatcher switch pattern (CFF)
        const dispatcherPattern = /repeat[\s\S]*?until\s+false|while\s+true\s+do[\s\S]*?if.*==.*then[\s\S]*?break/g;
        const dispatcherMatches = code.match(dispatcherPattern);
        if (dispatcherMatches && dispatcherMatches.length > 0) {
            evidence.push(`Dispatcher loops: ${dispatcherMatches.length}`);
            confidence += 0.2;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Helper: Shannon Entropy ---
    calculateEntropy(str) {
        if (!str || str.length === 0) return 0;
        const freq = {};
        for (const c of str) freq[c] = (freq[c] || 0) + 1;
        let entropy = 0;
        const len = str.length;
        for (const c in freq) {
            const p = freq[c] / len;
            if (p > 0) entropy -= p * Math.log2(p);
        }
        return entropy;
    }

    // --- Infer Version ---
    inferVersion(results, code) {
        const structural = results.find(r => r.layer === 'StructuralAnalysis');
        const pattern = results.find(r => r.layer === 'PatternMatch');

        if (structural && structural.evidence.some(e => /VM interpreter/i.test(e))) {
            return 'v5-vm';
        }
        if (structural && structural.evidence.some(e => /Proxy functions/i.test(e))) {
            return 'v3-proxy';
        }
        if (pattern && pattern.evidence.some(e => /CFF state variable/i.test(e))) {
            return 'v2-cff';
        }
        if (results.some(r => r.confidence > 0 && r.layer === 'SignatureScan')) {
            return 'v1-legacy';
        }
        return 'unknown';
    }
}


// ============================================================
// SECTION 2: DEOBFUSCATION ENGINE (CASCADING FALLBACK)
// ============================================================

export class PrometheusDeobfuscator {
    constructor() {
        this.levels = [
            { name: 'BasicCleanup', run: this.level1BasicCleanup.bind(this) },
            { name: 'StringDecryption', run: this.level2StringDecryption.bind(this) },
            { name: 'VariableRenaming', run: this.level3VariableRenaming.bind(this) },
            { name: 'ControlFlowUnflattening', run: this.level4CFFUnflattening.bind(this) },
            { name: 'ProxyResolution', run: this.level5ProxyResolution.bind(this) },
            { name: 'VMDeobfuscation', run: this.level6VMDeobfuscation.bind(this) },
        ];
    }

    /**
     * Main deobfuscation entry. Cascade through levels, stop when no more improvement.
     */
    deobfuscate(code, detectionResult = null) {
        if (!code) return { success: false, deobfuscatedCode: '', appliedLevels: [], notes: 'Empty input' };

        let current = code;
        const appliedLevels = [];
        const notes = [];

        // Kalau detectionResult kasih hint versi, reorder level (VM-first kalau v5)
        const orderedLevels = this.orderLevelsByHint(detectionResult);

        for (const level of orderedLevels) {
            try {
                const before = current;
                const result = level.run(current);

                if (result.changed && result.code !== before) {
                    current = result.code;
                    appliedLevels.push({
                        level: level.name,
                        changes: result.changes || 0,
                        notes: result.notes || null,
                    });

                    // Early exit kalau udah "clean" (entropy rendah, nggak ada _0x lagi)
                    if (this.isClean(current)) {
                        notes.push(`Early exit after ${level.name} — code appears clean`);
                        break;
                    }
                }
            } catch (err) {
                notes.push(`${level.name} failed: ${err.message}`);
            }
        }

        return {
            success: appliedLevels.length > 0,
            deobfuscatedCode: current,
            appliedLevels,
            notes: notes.join(' | '),
            finalEntropy: this.calculateEntropy(current),
        };
    }

    // --- Reorder levels berdasarkan version hint ---
    orderLevelsByHint(detection) {
        if (!detection || !detection.version) return this.levels;

        const v = detection.version;
        if (v === 'v5-vm') {
            // VM-based: coba VM deobf lebih awal
            return [
                this.levels[5], // VM
                this.levels[1], // String
                this.levels[4], // Proxy
                this.levels[0], // Cleanup
                this.levels[2], // Rename
                this.levels[3], // CFF
            ];
        }
        if (v === 'v3-proxy') {
            return [
                this.levels[4], // Proxy
                this.levels[1], // String
                this.levels[0], // Cleanup
                this.levels[2], // Rename
                this.levels[3], // CFF
                this.levels[5], // VM
            ];
        }
        // Default order
        return this.levels;
    }

    // --- LEVEL 1: Basic Cleanup ---
    level1BasicCleanup(code) {
        let result = code;
        let changes = 0;

        // Hapus komentar kosong / watermark Prometheus
        const before = result;
        result = result.replace(/--\s*\[\[\s*Prometheus[\s\S]*?\]\]/gi, '');
        result = result.replace(/--\s*Generated by Prometheus.*/gi, '');
        if (result !== before) changes++;

        // Hapus opaque predicates: if (complex_true_condition) then ... else <dead> end
        // Simplification: if true then X end → X
        const opaquePattern = /if\s+\(([^)]{10,})\)\s*then\s*([\s\S]*?)\s*end/g;
        result = result.replace(opaquePattern, (match, cond, body) => {
            // Kalau kondisi keliatan selalu true (contoh: (a==a) atau (0==0))
            if (/^\s*\(?[a-zA-Z_0-9]+\s*==\s*\1\)?\s*$/.test(cond) || /^\s*\(?\s*0\s*==\s*0\s*\)?\s*$/.test(cond)) {
                changes++;
                return body.trim();
            }
            return match;
        });

        // Hapus dead code setelah return dalam scope yang sama
        result = result.replace(/(return[^\n]*)\n[\s\S]*?(\n\s*end)/g, (match, ret, end) => {
            changes++;
            return ret + end;
        });

        return { code: result, changed: result !== code, changes };
    }

    // --- LEVEL 2: String Decryption ---
    level2StringDecryption(code) {
        let result = code;
        let changes = 0;

        // Pattern 1: string.char(a, b, c, ...) langsung
        result = result.replace(/string\.char\(([\d\s,]+)\)/g, (match, args) => {
            try {
                const bytes = args.split(',').map(s => parseInt(s.trim(), 10));
                if (bytes.every(n => !isNaN(n) && n >= 0 && n <= 255)) {
                    changes++;
                    return JSON.stringify(String.fromCharCode(...bytes));
                }
            } catch (e) { /* ignore */ }
            return match;
        });

        // Pattern 2: XOR decryption — string.char(bit32.bxor(byte, key))
        // Detect key dari konteks (biasanya konstanta di scope)
        const xorKeyMatch = code.match(/local\s+_0x[0-9a-fA-F]+\s*=\s*(\d+)/);
        if (xorKeyMatch) {
            const key = parseInt(xorKeyMatch[1], 10);
            result = result.replace(/string\.char\(\s*bit32\.bxor\(\s*(\d+)\s*,\s*\d+\s*\)\s*(?:,\s*bit32\.bxor\(\s*\d+\s*,\s*\d+\s*\)\s*)*\)/g, (match) => {
                try {
                    const byteMatches = [...match.matchAll(/bit32\.bxor\(\s*(\d+)\s*,\s*(\d+)\s*\)/g)];
                    const bytes = byteMatches.map(m => parseInt(m[1], 10) ^ parseInt(m[2], 10));
                    if (bytes.every(n => n >= 0 && n <= 255)) {
                        changes++;
                        return JSON.stringify(String.fromCharCode(...bytes));
                    }
                } catch (e) { /* ignore */ }
                return match;
            });
        }

        // Pattern 3: String table lookup — _0xTABLE[index]
        // Extract table definition dan replace lookup
        const tablePattern = /local\s+(_0x[0-9a-fA-F]+)\s*=\s*\{([^}]+)\}/;
        const tableMatch = result.match(tablePattern);
        if (tableMatch) {
            const tableName = tableMatch[1];
            const entries = tableMatch[2].split(',').map(s => {
                const trimmed = s.trim();
                // Parse string literal atau number
                if (/^["'].*["']$/.test(trimmed)) return JSON.parse(trimmed);
                const n = parseInt(trimmed, 10);
                return isNaN(n) ? null : n;
            });

            // Replace _0xTABLE[N] dengan value-nya
            const lookupPattern = new RegExp(`${tableName}\\[(\\d+)\\]`, 'g');
            result = result.replace(lookupPattern, (match, idx) => {
                const i = parseInt(idx, 10);
                if (entries[i] !== null && entries[i] !== undefined) {
                    changes++;
                    return typeof entries[i] === 'string' ? JSON.stringify(entries[i]) : entries[i];
                }
                return match;
            });
        }

        return { code: result, changed: result !== code, changes, notes: changes > 0 ? `Decrypted ${changes} string expressions` : null };
    }

    // --- LEVEL 3: Variable Renaming ---
    level3VariableRenaming(code) {
        let result = code;
        let changes = 0;

        // Collect all _0x... variables
        const hexVars = new Set();
        const varPattern = /\b(_0x[0-9a-fA-F]+)\b/g;
        let m;
        while ((m = varPattern.exec(code)) !== null) {
            hexVars.add(m[1]);
        }

        if (hexVars.size === 0) return { code: result, changed: false, changes: 0 };

        // Generate readable names: v1, v2, v3, ...
        const renameMap = {};
        let counter = 1;
        for (const v of hexVars) {
            renameMap[v] = `v${counter++}`;
        }

        // Replace (word boundary aware)
        for (const [oldName, newName] of Object.entries(renameMap)) {
            const re = new RegExp(`\\b${oldName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'g');
            result = result.replace(re, newName);
            changes++;
        }

        return { code: result, changed: result !== code, changes, notes: `Renamed ${changes} variables` };
    }

    // --- LEVEL 4: Control Flow Unflattening ---
    level4CFFUnflattening(code) {
        let result = code;
        let changes = 0;

        // Detect classic CFF pattern:
        // local state = 0x...
        // while true do
        //   if state == 0x... then ... state = 0x...
        //   elseif state == 0x... then ... state = 0x...
        //   ...
        // end
        const cffPattern = /local\s+(v\d+|_0x[0-9a-fA-F]+)\s*=\s*(0x[0-9a-fA-F]+|\d+)([\s\S]*?while\s+true\s+do[\s\S]*?end)/;
        const cffMatch = result.match(cffPattern);

        if (cffMatch) {
            const stateVar = cffMatch[1];
            const loopBody = cffMatch[3];

            // Extract branches: if/elseif state == X then <body>
            const branchPattern = /(?:if|elseif)\s+${stateVar}\s*==\s*(0x[0-9a-fA-F]+|\d+)\s*then([\s\S]*?)(?=(?:elseif|else|end))/g;
            // Re-bind pattern with actual stateVar
            const branchRegex = new RegExp(`(?:if|elseif)\\s+${stateVar}\\s*==\\s*(0x[0-9a-fA-F]+|\\d+)\\s*then([\\s\\S]*?)(?=(?:elseif|else|end))`, 'g');

            const branches = [];
            let bm;
            while ((bm = branchRegex.exec(loopBody)) !== null) {
                branches.push({
                    state: bm[1],
                    body: bm[2].trim(),
                });
            }

            if (branches.length >= 2) {
                // Sort by state value (asumsi state incrementing)
                branches.sort((a, b) => parseInt(a.state, 16) - parseInt(b.state, 16));

                // Reconstruct: sequential body, buang state assignment
                let reconstructed = branches.map(b => {
                    // Remove "stateVar = ..." dari body
                    const cleaned = b.body
                        .replace(new RegExp(`${stateVar}\\s*=\\s*(0x[0-9a-fA-F]+|\\d+)\\s*`), '')
                        .replace(/break\s*/g, '')
                        .trim();
                    return cleaned;
                }).filter(b => b.length > 0).join('\n');

                // Replace whole while loop dengan reconstructed
                result = result.replace(cffMatch[0], reconstructed);
                changes++;
            }
        }

        return { code: result, changed: result !== code, changes, notes: changes > 0 ? 'Unflattened control flow' : null };
    }

    // --- LEVEL 5: Proxy Function Resolution ---
    level5ProxyResolution(code) {
        let result = code;
        let changes = 0;

        // Detect proxy: function vN(...) return someGlobal(...) end
        const proxyPattern = /function\s+(v\d+|_0x[0-9a-fA-F]+)\s*\(([^)]*)\)\s*return\s+([a-zA-Z_][a-zA-Z0-9_.]*)\s*\(([^)]*)\)\s*end/g;

        const proxies = {};
        let pm;
        while ((pm = proxyPattern.exec(code)) !== null) {
            const proxyName = pm[1];
            const params = pm[2].split(',').map(s => s.trim()).filter(Boolean);
            const target = pm[3];
            const forwardedArgs = pm[4];

            // Kalau forwardedArgs cuma params yang sama urutan → inline-able
            const forwardedList = forwardedArgs.split(',').map(s => s.trim());
            if (JSON.stringify(params) === JSON.stringify(forwardedList)) {
                proxies[proxyName] = target;
            }
        }

        // Replace proxy calls with target
        for (const [proxyName, target] of Object.entries(proxies)) {
            const callPattern = new RegExp(`\\b${proxyName}\\s*\\(([^)]*)\\)`, 'g');
            result = result.replace(callPattern, (match, args) => {
                changes++;
                return `${target}(${args})`;
            });
        }

        // Remove proxy function definitions
        for (const proxyName of Object.keys(proxies)) {
            const defPattern = new RegExp(`function\\s+${proxyName}\\s*\\([^)]*\\)\\s*return\\s+[^)]+\\([^)]*\\)\\s*end\\s*`, 'g');
            result = result.replace(defPattern, '');
        }

        return { code: result, changed: result !== code, changes, notes: changes > 0 ? `Inlined ${Object.keys(proxies).length} proxy functions` : null };
    }

    // --- LEVEL 6: VM Deobfuscation (Latest Prometheus) ---
    level6VMDeobfuscation(code) {
        let result = code;
        let changes = 0;
        const notes = [];

        // Detect VM structure: dispatch table + while true loop + opcode handler
        // Pattern: local OPCODES = { [0] = func0, [1] = func1, ... }
        const dispatchPattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{([\s\S]*?)\}/;
        const dispatchMatch = result.match(dispatchPattern);

        if (dispatchMatch) {
            const tableName = dispatchMatch[1];
            const tableBody = dispatchMatch[2];

            // Cek apakah ini opcode table (banyak function entries)
            const funcEntries = (tableBody.match(/function/g) || []).length;
            if (funcEntries >= 5) {
                notes.push(`VM dispatch table detected: ${tableName} with ${funcEntries} opcodes`);

                // Extract bytecode array (biasanya local BYTECODE = {0, 1, 2, ...})
                const bytecodePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{\s*([\d\s,]+)\s*\}/;
                const bytecodeMatch = result.match(bytecodePattern);

                if (bytecodeMatch) {
                    const bytecodeName = bytecodeMatch[1];
                    const bytecode = bytecodeMatch[2].split(',').map(s => parseInt(s.trim(), 10)).filter(n => !isNaN(n));
                    notes.push(`Bytecode array: ${bytecodeName} (${bytecode.length} ops)`);

                    // Simplified: replace VM loop dengan注释 explaining structure
                    // Full VM deobf butuh emulator — di sini kita extract metadata aja
                    const vmLoopPattern = /while\s+true\s+do[\s\S]*?break[\s\S]*?end/;
                    if (vmLoopPattern.test(result)) {
                        result = result.replace(vmLoopPattern,
                            `-- [[ VM LOOP EXTRACTED BY KAIRO ]]\n-- Bytecode: [${bytecode.slice(0, 20).join(', ')}${bytecode.length > 20 ? ', ...' : ''}]\n-- Opcodes: ${funcEntries}\n-- Full VM emulation required for complete deobfuscation`);
                        changes++;
                    }
                }
            }
        }

        return {
            code: result,
            changed: result !== code,
            changes,
            notes: notes.length > 0 ? notes.join(' | ') : null,
        };
    }

    // --- Helpers ---
    calculateEntropy(str) {
        if (!str || str.length === 0) return 0;
        const freq = {};
        for (const c of str) freq[c] = (freq[c] || 0) + 1;
        let entropy = 0;
        const len = str.length;
        for (const c in freq) {
            const p = freq[c] / len;
            if (p > 0) entropy -= p * Math.log2(p);
        }
        return entropy;
    }

    isClean(code) {
        // Code dianggap "clean" kalau:
        // - Nggak ada _0x variable lagi
        // - Entropy rendah (< 4.0)
        // - Nggak ada while true do dispatcher
        const hasHexVars = /_0x[0-9a-fA-F]{4,}/.test(code);
        const entropy = this.calculateEntropy(code);
        const hasDispatcher = /while\s+true\s+do[\s\S]{200,}if.*==.*then/.test(code);

        return !hasHexVars && entropy < 4.0 && !hasDispatcher;
    }
}


