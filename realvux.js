export function processRealVux(code) {
    const detector = new RealVuxDetector();
    const detection = detector.detect(code);

    if (!detection.isRealVux) {
        return {
            success: false,
            detection,
            deobfuscation: null,
            message: 'Input tidak terdeteksi sebagai RealVuxObfuscate',
        };
    }

    const deobfuscator = new RealVuxDeobfuscator();
    const deobfuscation = deobfuscator.deobfuscate(code, detection);

    return {
        success: deobfuscation.success,
        detection,
        deobfuscation,
        message: deobfuscation.success
            ? `Deobfuscation selesai. Version: ${detection.version}. Applied: ${deobfuscation.appliedLevels.map(l => l.level).join(', ')}`
            : 'Detect sebagai RealVux tapi deobfuscation tidak menghasilkan perubahan signifikan',
    };
}
