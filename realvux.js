export class RealVuxDetector {
    constructor() {
        this.layers = [
            { name: 'SignatureScan', weight: 0.25, run: this.signatureScan.bind(this) },
            { name: 'VariableNamingPattern', weight: 0.20, run: this.variableNamingPattern.bind(this) },
            { name: 'VMStructureDetection', weight: 0.15, run: this.vmStructureDetection.bind(this) },
            { name: 'StringEncryptionPattern', weight: 0.15, run: this.stringEncryptionPattern.bind(this) },
            { name: 'AntiTamperDetection', weight: 0.10, run: this.antiTamperDetection.bind(this) },
            { name: 'EnvironmentSandboxing', weight: 0.10, run: this.environmentSandboxing.bind(this) },
            { name: 'HeuristicAnalysis', weight: 0.05, run: this.heuristicAnalysis.bind(this) },
        ];
    }

    detect(code) {
        if (!code || typeof code !== 'string') {
            return { isRealVux: false, confidence: 0, version: 'unknown', layers: [], error: 'Empty input' };
        }

        const results = [];
        let totalConfidence = 0;

        for (const layer of this.layers) {
            try {
                const layerResult = layer.run(code);
                results.push({
                    layer: layer.name,
                    confidence: layerResult.confidence,
                    evidence: layerResult.evidence || [],
                    versionHint: layerResult.versionHint || null,
                });
                totalConfidence += layerResult.confidence * layer.weight;
            } catch (err) {
                results.push({ layer: layer.name, confidence: 0, error: err.message });
            }
        }

        const isRealVux = totalConfidence >= 0.50;
        const version = this.inferVersion(results, code);

        return {
            isRealVux,
            confidence: Math.min(totalConfidence, 1.0),
            version,
            layers: results,
        };
    }

    // --- Layer 1: Signature / Watermark (KHAS REALVUX — MIXED CASE) ---
    signatureScan(code) {
        const evidence = [];
        let confidence = 0;

        const signatures = [
            { pattern: /RealVux/, label: 'RealVux mixed-case keyword' },
            { pattern: /realvux/i, label: 'realvux keyword' },
            { pattern: /real[_-]?vux/i, label: 'real-vux variant' },
            { pattern: /--\s*\[\[\s*RealVux/i, label: 'RealVux header comment' },
            { pattern: /REALVUX_V[0-9]/i, label: 'Version tag' },
            { pattern: /RVX_V[0-9]/i, label: 'RVX version tag' },
            { pattern: /Generated by RealVux/i, label: 'Generator signature' },
            { pattern: /RealVux\s+Obfuscator/i, label: 'Obfuscator comment' },
            { pattern: /--\s*Protected by RealVux/i, label: 'Protection watermark' },
            { pattern: /--\s*Obfuscated with RealVux/i, label: 'Generation tag' },
            { pattern: /realvux\.io/i, label: 'RealVux domain reference' },
            { pattern: /\bRealVux\b/, label: 'RealVux mixed-case standalone' },
        ];

        for (const sig of signatures) {
            if (sig.pattern.test(code)) {
                evidence.push(sig.label);
                confidence += 0.15;
            }
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 2: Variable Naming Pattern (KHAS REALVUX) ---
    variableNamingPattern(code) {
        const evidence = [];
        let confidence = 0;

        // RealVux signature: variable dengan prefix `rvx_`, `realvux_`, `vux_`, `rv_`
        const rvxPrefix = /local\s+((?:rvx|realvux|vux|rv|RVX|RV)[a-zA-Z0-9_]*)/g;
        const rvxMatches = [...code.matchAll(rvxPrefix)];

        if (rvxMatches.length >= 5) {
            evidence.push(`RealVux-prefixed variables: ${rvxMatches.length}`);
            confidence += 0.40;
        } else if (rvxMatches.length >= 2) {
            evidence.push(`RealVux-prefixed variables: ${rvxMatches.length}`);
            confidence += 0.20;
        }

        // Mix pattern: _0x... + rvx_...
        const mixPattern = /local\s+(_0x[0-9a-fA-F]+|(?:rvx|realvux|vux|rv|RVX|RV)[a-zA-Z0-9_]*)/g;
        const mixMatches = [...code.matchAll(mixPattern)];
        if (mixMatches.length >= 10) {
            evidence.push(`Mixed obfuscation variables: ${mixMatches.length}`);
            confidence += 0.25;
        }

        // Ratio: rvx vars / total vars
        const allVars = code.match(/local\s+([a-zA-Z_][a-zA-Z0-9_]*)/g) || [];
        const rvxStyleVars = allVars.filter(v => {
            const name = v.replace('local ', '');
            return /^(?:rvx|realvux|vux|rv|RVX|RV)/i.test(name) || /^_0x[0-9a-fA-F]+$/.test(name);
        });
        const ratio = allVars.length > 0 ? rvxStyleVars.length / allVars.length : 0;

        if (ratio > 0.5) {
            evidence.push(`RealVux-style variable ratio: ${(ratio * 100).toFixed(1)}%`);
            confidence += 0.30;
        } else if (ratio > 0.25) {
            evidence.push(`RealVux-style variable ratio: ${(ratio * 100).toFixed(1)}%`);
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 3: VM Structure Detection (RealVux v2+) ---
    vmStructureDetection(code) {
        const evidence = [];
        let confidence = 0;

        // VM dispatch table
        const dispatchPattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{[\s\S]*?\[\d+\]\s*=\s*function/g;
        const dispatchMatches = code.match(dispatchPattern);
        if (dispatchMatches && dispatchMatches.length >= 5) {
            evidence.push(`VM dispatch table: ${dispatchMatches.length} opcodes`);
            confidence += 0.35;
        }

        // Bytecode array
        const bytecodePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{\s*[\d\s,]{80,}\s*\}/;
        if (bytecodePattern.test(code)) {
            evidence.push('Bytecode array detected');
            confidence += 0.20;
        }

        // VM loop
        const vmLoopPattern = /while\s+true\s+do[\s\S]{300,}if\s+[a-zA-Z_][a-zA-Z0-9_]*\s*==\s*\d+/;
        if (vmLoopPattern.test(code)) {
            evidence.push('VM dispatch loop detected');
            confidence += 0.20;
        }

        // Stack operations
        const stackPattern = /table\.insert\([^,]+,\s*[^)]+\)|table\.remove\([^)]+\)/g;
        const stackMatches = code.match(stackPattern);
        if (stackMatches && stackMatches.length >= 8) {
            evidence.push(`Stack operations: ${stackMatches.length}`);
            confidence += 0.15;
        }

        // PC (program counter)
        const pcPattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*0[\s\S]*?while\s+true\s+do[\s\S]*?\1\s*=\s*\1\s*\+\s*1/;
        if (pcPattern.test(code)) {
            evidence.push('Program counter (PC) pattern detected');
            confidence += 0.20;
        }

        return { confidence: Math.min(confidence, 1.0), evidence, versionHint: confidence > 0.4 ? 'v2-vm' : null };
    }

    // --- Layer 4: String Encryption Pattern (KHAS REALVUX — MULTI-LAYER) ---
    stringEncryptionPattern(code) {
        const evidence = [];
        let confidence = 0;

        // Multi-layer: XOR + rotation + substitution
        // Pattern: string.char((bit32.bxor(N, K) + offset) % 256)
        const multiLayerPattern = /string\.char\s*\(\s*\(\s*bit32\.bxor\s*\([^)]+\)\s*[+\-]\s*\d+\s*\)\s*%\s*256\s*\)/g;
        const multiLayerMatches = code.match(multiLayerPattern);
        if (multiLayerMatches && multiLayerMatches.length >= 3) {
            evidence.push(`Multi-layer cipher (XOR + rotation): ${multiLayerMatches.length}`);
            confidence += 0.30;
        }

        // Rotation cipher: string.char((byte + N) % 256)
        const rotationPattern = /string\.char\s*\(\s*\(\s*\d+\s*[+\-]\s*\d+\s*\)\s*%\s*256\s*\)/g;
        const rotationMatches = code.match(rotationPattern);
        if (rotationMatches && rotationMatches.length >= 3) {
            evidence.push(`Rotation cipher: ${rotationMatches.length}`);
            confidence += 0.20;
        }

        // XOR + substitution combo
        const xorSubPattern = /string\.char\s*\(\s*bit32\.bxor\s*\(\s*(\d+)\s*,\s*(\d+)\s*\)\s*([+\-])\s*(\d+)\s*\)/g;
        const xorSubMatches = code.match(xorSubPattern);
        if (xorSubMatches && xorSubMatches.length >= 3) {
            evidence.push(`XOR + substitution: ${xorSubMatches.length}`);
            confidence += 0.20;
        }

        // Decrypt function dengan loop kompleks
        const decryptFuncPattern = /function\s+[a-zA-Z_][a-zA-Z0-9_]*\s*\([^)]*\)[\s\S]{100,}for\s+[a-zA-Z_][a-zA-Z0-9_]*\s*=\s*\d+\s*,\s*#[\s\S]*?bit32\.[\s\S]*?return\s+string\.char/g;
        if (decryptFuncPattern.test(code)) {
            evidence.push('Complex decrypt function detected');
            confidence += 0.20;
        }

        // String table dengan encrypted entries
        const stringTablePattern = /local\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\{\s*"[^"]{10,}"[\s\S]*?\}/;
        if (stringTablePattern.test(code)) {
            evidence.push('Encrypted string table');
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 5: Anti-Tamper Detection ---
    antiTamperDetection(code) {
        const evidence = [];
        let confidence = 0;

        // Integrity check function
        const integrityPattern = /function\s+[a-zA-Z_][a-zA-Z0-9_]*\s*\(\s*\)[\s\S]{100,}return\s+(true|false)/g;
        const integrityMatches = code.match(integrityPattern);
        if (integrityMatches && integrityMatches.length >= 3) {
            evidence.push(`Integrity check functions: ${integrityMatches.length}`);
            confidence += 0.30;
        }

        // Anti-debug
        const antiDebugPattern = /debug\.info|getfenv|setfenv|debug\.getinfo|debug\.sethook/g;
        const antiDebugMatches = code.match(antiDebugPattern);
        if (antiDebugMatches && antiDebugMatches.length >= 4) {
            evidence.push(`Anti-debug checks: ${antiDebugMatches.length}`);
            confidence += 0.25;
        }

        // Environment manipulation
        const envCheckPattern = /_G\[["'][^"']+["']\]|_ENV\[["'][^"']+["']\]/g;
        const envMatches = code.match(envCheckPattern);
        if (envMatches && envMatches.length >= 3) {
            evidence.push(`Environment manipulation: ${envMatches.length}`);
            confidence += 0.20;
        }

        // Bytecode integrity hash
        const hashPattern = /function\s+[a-zA-Z_][a-zA-Z0-9_]*\s*\([^)]*\)[\s\S]{50,}return\s+["'][0-9a-fA-F]{16,}["']/g;
        if (hashPattern.test(code)) {
            evidence.push('Bytecode integrity hash detected');
            confidence += 0.25;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 6: Environment Sandboxing ---
    environmentSandboxing(code) {
        const evidence = [];
        let confidence = 0;

        // RealVux sering bikin sandbox environment
        const sandboxPattern = /local\s+[a-zA-Z_][a-zA-Z0-9_]*\s*=\s*\{\}[\s\S]*?setfenv\s*\(\s*[a-zA-Z_][a-zA-Z0-9_]*\s*,/g;
        if (sandboxPattern.test(code)) {
            evidence.push('Environment sandboxing detected');
            confidence += 0.30;
        }

        // _G/_ENV manipulation agresif
        const gManipPattern = /_G\[["'][^"']+["']\]\s*=/g;
        const gMatches = code.match(gManipPattern);
        if (gMatches && gMatches.length >= 3) {
            evidence.push(`_G manipulation: ${gMatches.length}`);
            confidence += 0.20;
        }

        // Custom environment table
        const envTablePattern = /local\s+[a-zA-Z_][a-zA-Z0-9_]*\s*=\s*\{[\s\S]*?print[\s\S]*?string[\s\S]*?table[\s\S]*?\}/;
        if (envTablePattern.test(code)) {
            evidence.push('Custom environment table detected');
            confidence += 0.20;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    // --- Layer 7: Heuristic Analysis ---
    heuristicAnalysis(code) {
        const evidence = [];
        let confidence = 0;

        // High entropy strings
        const stringLiterals = code.match(/"([^"\\]|\\.)*"/g) || [];
        let highEntropyStrings = 0;
        for (const s of stringLiterals) {
            if (this.calculateEntropy(s) > 4.5 && s.length > 20) {
                highEntropyStrings++;
            }
        }
        if (highEntropyStrings > 5) {
            evidence.push(`High-entropy strings: ${highEntropyStrings}`);
            confidence += 0.25;
        }

        // Minified structure
        const lines = code.split('\n').filter(l => l.trim().length > 0);
        const avgLineLength = code.length / Math.max(lines.length, 1);
        if (avgLineLength > 5000 && lines.length < 10) {
            evidence.push(`Minified: ${lines.length} lines, avg ${avgLineLength.toFixed(0)} chars/line`);
            confidence += 0.20;
        }

        // Function density
        const functionCount = (code.match(/\bfunction\b/g) || []).length;
        const localCount = (code.match(/\blocal\b/g) || []).length;
        if (localCount > 0 && functionCount / localCount > 0.35) {
            evidence.push(`High function/local ratio: ${(functionCount / localCount).toFixed(2)}`);
            confidence += 0.15;
        }

        return { confidence: Math.min(confidence, 1.0), evidence };
    }

    calculateEntropy(str) {
        if (!str || str.length === 0) return 0;
        const freq = {};
        for (const c of str) freq[c] = (freq[c] || 0) + 1;
        let entropy = 0;
        const len = str.length;
        for (const c in freq) {
            const p = freq[c] / len;
            if (p > 0) entropy -= p * Math.log2(p);
        }
        return entropy;
    }

    inferVersion(results, code) {
        const vm = results.find(r => r.layer === 'VMStructureDetection');
        const antiTamper = results.find(r => r.layer === 'AntiTamperDetection');
        const sandbox = results.find(r => r.layer === 'EnvironmentSandboxing');

        if (vm && vm.confidence > 0.5 && antiTamper && antiTamper.confidence > 0.4 && sandbox && sandbox.confidence > 0.3) {
            return 'v3-vm-antitamper-sandbox';
        }
        if (vm && vm.confidence > 0.5 && antiTamper && antiTamper.confidence > 0.4) {
            return 'v2-vm-antitamper';
        }
        if (vm && vm.confidence > 0.5) {
            return 'v2-vm';
        }
        if (sandbox && sandbox.confidence > 0.3 && antiTamper && antiTamper.confidence > 0.3) {
            return 'v1-sandbox-antitamper';
        }
        if (antiTamper && antiTamper.confidence > 0.3) {
            return 'v1-antitamper';
        }
        if (results.some(r => r.confidence > 0 && r.layer === 'SignatureScan')) {
            return 'v1-legacy';
        }
        return 'unknown';
    }
}


