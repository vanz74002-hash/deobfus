// ============================================================

export function processPSU(code) {
    const detector = new PSUDetector();
    const detection = detector.detect(code);

    if (!detection.isPSU) {
        return {
            success: false,
            detection,
            deobfuscation: null,
            message: 'Input tidak terdeteksi sebagai PSU obfuscator',
        };
    }

    const deobfuscator = new PSUDeobfuscator();
    const deobfuscation = deobfuscator.deobfuscate(code, detection);

    return {
        success: deobfuscation.success,
        detection,
        deobfuscation,
        message: deobfuscation.success
            ? `Deobfuscation selesai. Version: ${detection.version}. Applied: ${deobfuscation.appliedLevels.map(l => l.level).join(', ')}`
            : 'Detect sebagai PSU tapi deobfuscation tidak menghasilkan perubahan signifikan',
    };
}
